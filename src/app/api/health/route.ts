/** Ответ считается сорванным, если база молчит дольше. Короткий срок
 *  намеренно: сторож доступности, который сам висит минуту, — это второй
 *  отказ, а не измерение первого. */
const DB_TIMEOUT_MS = 2500;

/** Сколько секунд CDN держит удачный ответ. Тридцать–шестьдесят: меньше
 *  бессмысленно (пинг раз в 5 минут всё равно мимо кеша), больше —
 *  задерживает тревогу. Сличается сторожем `check:health-route`. */
const CACHE_SECONDS = 45;

export const dynamic = "force-dynamic";
export const runtime = "nodejs";

function withTimeout<T>(promise: Promise<T>, ms: number): Promise<T> {
  return new Promise<T>((resolve, reject) => {
    const timer = setTimeout(() => reject(new Error("timeout")), ms);
    promise.then(
      (value) => {
        clearTimeout(timer);
        resolve(value);
      },
      (error) => {
        clearTimeout(timer);
        reject(error instanceof Error ? error : new Error("db"));
      },
    );
  });
}

export async function GET() {
  const startedAt = Date.now();
  // Короткий идентификатор живого деплоя. Не личные данные и не секрет:
  // ровно та же величина уже стоит на каждой странице прода в метке
  // `sentry-release`. Нужен для отката — по нему видно, какой именно
  // деплой сейчас отвечает.
  const commit = (process.env.VERCEL_GIT_COMMIT_SHA ?? "").slice(0, 7) || null;

  try {
    await withTimeout(db.$queryRaw`SELECT 1`, DB_TIMEOUT_MS);
  } catch {
    // Тело у отказа обязательно. Пятисотка без тела — это «что-то
    // случилось», и внешнему сторожу с ней делать нечего; 503 со словом
    // `db_unreachable` отличает «база молчит» от «функция не поднялась»
    // (тогда ответа не будет вовсе) и от «страница сломана» (это ловит
    // браузерный прогон, а не этот адрес).
    return NextResponse.json(
      { status: HEALTH_DOWN_TOKEN, ok: false, db: "down", reason: "db_unreachable", ms: Date.now() - startedAt, commit },
      { status: 503, headers: { "Cache-Control": "no-store", "X-Robots-Tag": "noindex, nofollow" } },
    );
  }

  return NextResponse.json(
    { status: HEALTH_OK_TOKEN, ok: true, db: "up", ms: Date.now() - startedAt, commit },
    {
      status: 200,
      headers: {
        "Cache-Control": `public, max-age=0, s-maxage=${CACHE_SECONDS}, stale-while-revalidate=15`,
        "X-Robots-Tag": "noindex, nofollow",
      },
    },
  );
}
