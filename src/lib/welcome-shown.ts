/** Имя куки. Одно написание на весь проект. */
export const WELCOME_SHOWN_COOKIE = "rf-welcome-shown";

/** Двое суток. Не сутки: у ученика, перешедшего часовой пояс, «сегодня»
 *  может отъехать назад, и кука не должна умереть раньше своего дня. Не
 *  год: значение бесполезно на следующий же день, и хранить его дольше
 *  незачем. */
export const WELCOME_SHOWN_MAX_AGE_SECONDS = 60 * 60 * 24 * 2;

/** Значение отметки: кому и за какой день. Идентификатор нужен потому,
 *  что одним устройством пользуются двое, и приветствие второму человеку
 *  не должно съедаться первым. */
export function welcomeShownValue(userId: string, dateKey: string): string {
  return `${userId}:${dateKey}`;
}

/** Один местный день — значение отметки на аккаунте. Строка «YYYY-MM-DD»
 *  в зоне аккаунта, та же, что у отметки занятия; сравнение всегда
 *  строгое равенство, потому что ключ дня — единственная форма, в которой
 *  этот вопрос вообще задаётся. */
export function greetedOnAccountToday(
  storedDateKey: string | null | undefined,
  todayKey: string,
): boolean {
  return typeof storedDateKey === "string" && storedDateKey === todayKey;
}

/** Адрес, по которому браузер сообщает серверу, что приветствие показано.
 *  Одно написание на весь проект — им же пользуется сторож. */
export const WELCOME_SHOWN_ENDPOINT = "/api/welcome-shown";
