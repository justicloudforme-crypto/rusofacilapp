/** Никто не вошёл. Значение поля, а не отсутствие поля. */
export const GUEST_OWNER = "guest";

/**
 * Кто пишет прямо сейчас. Модульная переменная, а не контекст React:
 * писатель (`setWordKnown`) — обычная функция, которую зовут из
 * обработчика, и протаскивать в неё владельца через пять слоёв свойств
 * значило бы менять четыре компонента ради одного поля. Тот же приём, что
 * у учёта прижатых слоёв (`pinned-layers.ts`).
 */
let owner: string = GUEST_OWNER;

/** Чья запись получится, если написать сейчас. */
export function currentOwner(): string {
  return owner;
}

/**
 * Запомнить владельца. Зовётся из `syncKnownWords()`: ответ сервера — это
 * и есть единственный достоверный ответ на вопрос «кто вошёл» у клиента.
 * `null` — сервер ответил 401, то есть никто.
 */
export function rememberOwner(id: string | null): void {
  owner = id ?? GUEST_OWNER;
}

/** Строка учебной истории с происхождением. */
export interface Owned {
  by?: string;
}

/**
 * Что остаётся в карте после выхода: только то, что написано БЕЗ сессии.
 * Возвращает новую карту; пустая означает «ключ можно убрать целиком».
 */
export function keepGuestOwned<T extends Owned>(map: Record<string, T>): Record<string, T> {
  const out: Record<string, T> = {};
  for (const [id, entry] of Object.entries(map)) {
    if (entry?.by === GUEST_OWNER) out[id] = entry;
  }
  return out;
}

/**
 * Что остаётся в карте при ПЕРЕКЛЮЧЕНИИ аккаунта: свои записи и гостевые.
 * Чужие уходят — иначе история одного человека досталась бы другому на
 * том же устройстве.
 *
 * Наследство (поля нет) остаётся: на устройстве, где ни одна строка не
 * помечена, вход под вторым аккаунтом иначе стёр бы всё сразу, а это
 * поведение не менялось с 7.199 и менять его этим долгом незачем.
 */
export function dropOtherOwners<T extends Owned>(map: Record<string, T>, current: string): Record<string, T> {
  const out: Record<string, T> = {};
  for (const [id, entry] of Object.entries(map)) {
    const by = entry?.by;
    if (by === undefined || by === GUEST_OWNER || by === current) out[id] = entry;
  }
  return out;
}
