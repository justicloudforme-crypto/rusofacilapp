"use client";

import { useEffect, useState } from "react";
import type { FlashcardLevel } from "./types";
import { EMPTY_SUMMARY, fetchCategorySummary, type CategorySummaryResponse } from "./summary-client";

/**
 * ПЕРЕПИСЬ ТЕМ ОДНОГО РАЗРЕЗА — ОДИН РАЗ НА ВСЕ ЧЕТЫРЕ РЕЖИМА СЛОВАРЯ
 * (заход 7.199, часть 1).
 *
 * ====================================================================
 * ЧТО БЫЛО СНЯТО НА ТЕЛЕФОНЕ
 * ====================================================================
 *
 * Гость и подписчик, обе локали: на странице «Vocabulario en tarjetas»
 * выбран уровень C1 — первые ~1,5 с числа верные («Trabajo y estudios ·
 * 0/51», плашка «988 palabras del nivel C1 cerradas»), затем блок
 * «Continuar» подменяется карточками ЧУЖОГО разреза («молоко»,
 * «арендатор», «гибкий график») с серыми полосками вместо чисел, плашка
 * C1 исчезает, а на плитках тем числа превращаются в заглушки. Так висит
 * не меньше 18 секунд. Повторное нажатие на тот же уровень возвращает
 * правильные числа.
 *
 * ====================================================================
 * ПРИЧИНА — ГОНКА ДВУХ ОТВЕТОВ, И ОНА БЫЛА В ЧЕТЫРЁХ ФАЙЛАХ СРАЗУ
 * ====================================================================
 *
 * `FlashcardsApp`, `RecallApp`, `MatchApp` и `FillBlankApp` держали по
 * одинаковому эффекту:
 *
 *     useEffect(() => {
 *       fetchCategorySummary(levelFilter).then((body) => { …setState… });
 *     }, [levelFilter, …]);
 *
 * Ни одного признака отмены. Открытие страницы запускает запрос на разрез
 * «все уровни», нажатие на C1 — второй запрос; ответ на «все» тяжелее и
 * приходит ПОЗЖЕ, после чего его обработчик спокойно перезаписывает
 * состояние, посчитанное по C1. Дальше `summaryLevel` равен `null`
 * («все»), а `levelFilter` — «C1», и оба потребителя чисел
 * (`CategoryGrid.tsx:107`, `ContinueStrip` через проп `ready`) печатают
 * заглушку — навсегда, потому что снять её может только НОВЫЙ ответ, а
 * запрашивать его больше некому. Ровно это владелец и снял на видео: и
 * вечную серую полосу, и чужие слова в «Продолжить».
 *
 * ====================================================================
 * ПОЧЕМУ ПРАВИЛО ЖИВЁТ ЗДЕСЬ, А НЕ ЧЕТЫРЕ РАЗА
 * ====================================================================
 *
 * Потому что четыре копии одного эффекта и дали четыре копии одного
 * дефекта. Здесь оно одно, и обе его половины видно рядом:
 *
 *   1. `cancelled` — ответ на ОТМЕНЁННЫЙ запрос не применяется вовсе.
 *      Это и есть починка гонки: React зовёт уборку эффекта в тот же
 *      миг, когда меняется уровень, то есть до того, как опоздавший
 *      ответ доедет.
 *   2. Подпись разреза приходит с ответом (`summary-client.ts`), и она
 *      стоит ВСЕГДА — даже у неудачного запроса. Поэтому заглушка не
 *      может жить дольше одного запроса: любой исход её снимает.
 *
 * Отмена — не «на всякий случай»: без неё пункт 2 сам по себе дефект не
 * закрывает, потому что опоздавший ответ тоже подписан — своим,
 * предыдущим разрезом.
 */
export interface CategorySummaryState {
  /** Числа переписи. Пока `summaryLevel === undefined` — пустые. */
  summary: CategorySummaryResponse;
  /**
   * Разрез, к которому относятся числа в руках: `undefined` — ответа на
   * текущий разрез ещё нет, `null` — «все уровни», строка — этот уровень.
   * Тот самый признак, который читают `CategoryGrid` и `ContinueStrip`.
   */
  summaryLevel: string | null | undefined;
}

export function useCategorySummary(
  level: FlashcardLevel | "all",
  /** Что ещё обязано перезапросить перепись: раунд, отметка «знаю»,
   *  завершение игры. Длина массива у одного места вызова постоянна —
   *  React требует именно этого, а не одинаковых значений. */
  reloadKeys: readonly unknown[] = [],
): CategorySummaryState {
  const [state, setState] = useState<CategorySummaryState>({
    summary: EMPTY_SUMMARY,
    summaryLevel: undefined,
  });

  useEffect(() => {
    let cancelled = false;
    void fetchCategorySummary(level).then((body) => {
      if (cancelled) return;
      setState({ summary: body, summaryLevel: body.level });
    });
    return () => {
      cancelled = true;
    };
    // Массив зависимостей собирается из уровня и ключей перезапроса —
    // правило eslint не умеет читать раскрытие, а длина у одного места
    // вызова постоянна, и это то единственное, что важно React.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [level, ...reloadKeys]);

  return state;
}
