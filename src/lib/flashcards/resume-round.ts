/**
 * Поставить в начало круга ту карточку, на которой человек остановился.
 *
 * Режимы «Вспомни», «Заполни пропуск» и «Соедини пары» строят КРУГ —
 * выборку из темы по интервальному повторению, а не список по порядку.
 * Поэтому «открыть то самое слово» здесь значит не «встать на позицию N»
 * (позиции у круга своей нет), а «это слово — первое, что человек
 * увидит». Ровно это и делается ниже, и только это.
 *
 * Три случая, и все три названы:
 *
 *   1. карточка уже в круге — переставляется в начало, состав круга не
 *      меняется ни на одну строку;
 *   2. карточки в круге нет, но она есть в теме — становится первой
 *      ВМЕСТО прежней первой; размер круга сохраняется, иначе круг из 10
 *      молча стал бы кругом из 11 и разошёлся бы со счётчиком;
 *   3. карточки нет нигде (стёрли, сменился фильтр уровня) — круг
 *      возвращается как есть. Не падение: тема просто открывается с
 *      начала, как открывалась до 09.09.2026 всегда.
 */
export function resumeRoundAt<T extends { id: string }>(
  round: readonly T[],
  pool: readonly T[],
  startCardId: string | null | undefined,
): T[] {
  if (!startCardId || round.length === 0) return [...round];

  const inRound = round.findIndex((c) => c.id === startCardId);
  if (inRound > 0) {
    const copy = [...round];
    const [card] = copy.splice(inRound, 1);
    return [card, ...copy];
  }
  if (inRound === 0) return [...round];

  const fromPool = pool.find((c) => c.id === startCardId);
  if (!fromPool) return [...round];
  return [fromPool, ...round.slice(1)];
}
