// Fisher-Yates shuffle shared by every flashcard-based game mode (recall
// trainer rounds, match-game rounds) that needs to randomize a card pool.
export function shuffle<T>(items: T[]): T[] {
  const copy = [...items];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}
