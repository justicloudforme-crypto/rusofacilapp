import { DOWNLOADS_CACHE_NAME, GENERATION_CACHE_NAME, PAGE_CACHE_PREFIX } from "./sw-cache-names";

/**
 * ЧТО ОСТАЁТСЯ В БРАУЗЕРЕ ПОСЛЕ ВЫХОДА ИЗ АККАУНТА (заход 7.198, часть 1).
 *
 * ====================================================================
 * ОТКУДА ПРАВИЛО
 * ====================================================================
 *
 * Жалоба владельца была про сессию: вышел, закрыл приложение, открыл —
 * снова под аккаунтом. Её причина оказалась нативной (хранилище кук
 * webview не успевало записаться на диск, см. `MainActivity.onPause`).
 *
 * Но у неё была вторая, независимая половина, и она живёт здесь.
 * Страницы сайта у service worker'а обслуживаются `NetworkFirst`
 * (`src/app/sw.ts`): каждая открытая страница КЛАДЁТСЯ В КЕШ, и страницы
 * вошедшего человека — тоже. В кеше остаются его имя в шапке, его
 * «Продолжить», его календарь, его профиль. Выход не трогал ни одной из
 * этих копий: сервер отдаёт гостя, а копия про это не знает и всплывает,
 * как только сеть молчит.
 *
 * Измерено на собранной сборке (`npm run check:signed-out`): после входа
 * и трёх открытых страниц в кешах лежат личные документы; до этой правки
 * выход оставлял их все.
 *
 * ====================================================================
 * ЧТО ИМЕННО УДАЛЯЕТСЯ, И ПОЧЕМУ НЕ ВСЁ
 * ====================================================================
 *
 * Только кеши ДОКУМЕНТОВ — те четыре семейства, которые заводит
 * `pageCacheNames` (плюс их безымянные предшественники из @serwist/next,
 * которые ещё живут у вернувшегося посетителя). Личные данные бывают
 * только в них: остальное — шрифты, картинки, озвучка и файлы
 * `/_next/static/…` с хешем содержимого в имени — одинаково у всех и
 * стоит дорого (озвучка рассказа — мегабайты). Выбрасывать её при выходе
 * значило бы платить чужими мегабайтами за чужую же приватность.
 *
 * Удаляются кеши ВСЕХ сборок, а не только текущей: вернувшийся посетитель
 * носит в себе и прошлые, и личные копии в них ровно те же.
 */

/** Фиксированные имена, которыми @serwist/next пользовался до долга 14.
 *  У вернувшегося посетителя они ещё есть, и личные копии в них те же. */
export const LEGACY_PAGE_CACHES = ["pages", "pages-rsc", "pages-rsc-prefetch", "others"];

/** Признак в адресе, по которому страница после выхода узнаёт, что чистить
 *  кеш надо именно сейчас. Он же — единственное, что связывает маршрут
 *  выхода и уборщик на странице. */
export const SIGNED_OUT_PARAM = "signedout";

/**
 * Кеши, способные нести личный документ. Имена берутся из ЖИВОГО списка
 * `caches.keys()`, а не собираются по памяти: имя кеша текущей сборки
 * содержит её отпечаток, и знать его заранее странице неоткуда.
 */
export function personalPageCaches(existing: readonly string[]): string[] {
  return existing.filter((name) => LEGACY_PAGE_CACHES.includes(name) || name.startsWith(PAGE_CACHE_PREFIX));
}

/**
 * СМЕНА ВЛАДЕЛЬЦА КОПИЙ БЕЗ ВЫХОДА — Ж.4 (аудит 7.241; заход 7.243).
 *
 * Выход чистит копии страниц (выше), вход — не чистил. Шапка документа
 * рисуется сервером под того, кто пришёл, и копия, снятая гостем до
 * входа (например «Biblioteca de cuentos» с гостевым «≡»), жила после
 * входа дальше. Та же дыра наоборот: учётка A → вход учёткой B без выхода —
 * в копиях шапка и данные A.
 *
 * Владельца называет сервер (макет: `ownerScopeFor(user.id)` или «anon»),
 * страница помнит прошлого в `localStorage` и при смене чистит:
 *   • гость → учётка: копии разделов и документов, но НЕ скачанное —
 *     его скачал гость на этом телефоне, и теперь это скачанное текущего
 *     владельца; и не метку поколения (её ведёт выкат);
 *   • учётка → другой владелец: ровно как выход, скачанное тоже — оно
 *     чужое.
 * Очередь ответов `rf-progress-outbox` — IndexedDB, а не кеш: сюда она не
 * попадает по построению (правило 7.237 — очередь не стирается никогда).
 * Первый запуск без записи о прошлом владельце ничего не чистит: сравнить
 * не с чем.
 */
export const PAGE_OWNER_KEY = "rf-pages-owner";
export const GUEST_PAGE_OWNER = "anon";

export function ownerChangePurge(existing: readonly string[], previous: string | null, current: string): string[] {
  if (previous === null || previous === current) return [];
  const personal = personalPageCaches(existing);
  if (previous !== GUEST_PAGE_OWNER) return personal;
  return personal.filter((name) => name !== DOWNLOADS_CACHE_NAME && name !== GENERATION_CACHE_NAME);
}
