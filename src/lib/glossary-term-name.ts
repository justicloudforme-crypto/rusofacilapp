/**
 * Какое из двух названий грамматического термина — ГЛАВНОЕ, и какое идёт
 * второй строкой. Одна функция на весь сайт.
 *
 * ЗАЧЕМ. До 19.09.2026 в ОБЕИХ локалях главным названием термина
 * печаталось поле `term` — испанское («caso vocativo», «artículo»), — а
 * русский эквивалент был либо подписанной строкой рядом, либо не
 * печатался вовсе. На `/ru` это давало экран, где все подписи вокруг
 * русские («0/4 усвоено», «Уже знаете эти термины?»), а сами термины
 * названы по-испански: русская версия читалась как незаконченная. Снято
 * владельцем на видео 18.09.2026, измерено в заходе 7.212 (часть 3.1):
 * витрин, печатающих название термина, 13, и все 13 в обеих локалях
 * печатали `term`.
 *
 * РЕШЕНИЕ ВЛАДЕЛЬЦА от 19.09.2026 — вариант Б из трёх, предложенных
 * в 7.212:
 *
 *   в локали `ru` главным названием термина печатается РУССКИЙ
 *   эквивалент, испанское название идёт второй строкой, мельче;
 *   в локали `es` — наоборот, главным остаётся испанское название.
 *
 * Отвергнутый вариант В (сменить только экранные витрины, а `<title>` и
 * разметку оставить) плох ровно одним: у одного и того же термина на
 * экране и в заголовке вкладки оказались бы РАЗНЫЕ названия. Поэтому
 * функция одна и её зовут все витрины, включая поисковые.
 *
 * ДВА СЛУЧАЯ, КОТОРЫЕ ИЗМЕРЕНЫ ПО БОЕВОЙ БАЗЕ 19.09.2026 (119 терминов,
 * только SELECT) и потому решены здесь, а не оставлены на «как получится»:
 *
 *   1. Пустой русский эквивалент — таких сегодня **0 из 119**. Но правило
 *      обязано отвечать и на этот случай, иначе на экране появится
 *      молчаливая пустота вместо названия: при пустом (или состоящем из
 *      одних пробелов) `russianEquivalent` главным остаётся испанское
 *      название, второй строки нет.
 *   2. Русский эквивалент ДОСЛОВНО совпадает с испанским названием —
 *      таких **6 из 119**, и все шесть это пары глаголов движения,
 *      записанные кириллицей в обоих полях («бежать / бегать», «ехать /
 *      ездить», «идти / ходить», «лететь / летать», «нести / носить»,
 *      «плыть / плавать»). Печатать такую вторую строку значило бы
 *      напечатать то же самое дважды. Второй строки нет.
 *
 * Сторож правила — `scripts/check-term-name-locale.ts`
 * (`npm run check:term-name`), двусторонний: он требует и того, что на
 * `/ru` главное имя русское, и того, что на `/es` оно испанское.
 */

/** Ровно те два поля, которые решают вопрос. Намеренно уже, чем
 * `GlossaryTermData`: половина витрин работает с выборкой в две-три
 * колонки, и требовать от них полную запись значило бы читать из базы
 * лишнее. */
export interface GlossaryTermNameSource {
  term: string;
  russianEquivalent?: string | null;
}

export interface GlossaryTermNames {
  /** Главное название: то, что печатается крупно, попадает в `<title>`,
   * в `h1` и в разметку для поисковика. */
  primary: string;
  /** Второе название — мельче и под главным. `null` означает «второй
   * строки нет вовсе», а не «пустая строка»: витрина обязана в этом
   * случае не рисовать разделитель и не оставлять дыру. */
  secondary: string | null;
}

/**
 * @param lang локаль страницы (`"ru"` | `"es"`). Строка, а не `Locale`,
 *   потому что часть витрин достаёт её из `usePathname()` и там это
 *   обычный `string`; всё, что не `"ru"`, ведёт себя как `"es"`.
 */
export function glossaryTermNames(term: GlossaryTermNameSource, lang: string): GlossaryTermNames {
  const spanish = term.term.trim();
  const russian = (term.russianEquivalent ?? "").trim();

  if (lang !== "ru") return { primary: spanish, secondary: null };
  if (russian === "") return { primary: spanish, secondary: null };
  return { primary: russian, secondary: russian === spanish ? null : spanish };
}

/** Одно главное название — для мест, где второй строке негде поместиться
 * (`<title>`, `name` в разметке JSON-LD, подстановка `{term}` в подпись). */
export function glossaryTermPrimaryName(term: GlossaryTermNameSource, lang: string): string {
  return glossaryTermNames(term, lang).primary;
}
