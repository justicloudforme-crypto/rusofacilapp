/**
 * Одна форма записи русского слова — для сличения тапнутого слова со
 * СВОИМ банком переводов (долг 169, заход 7.188).
 *
 * ПРАВИЛО НАМЕРЕННО СКУПОЕ, и вот почему. Ложное совпадение здесь хуже
 * отсутствия перевода: «нет перевода» ученик видит как «нет перевода» и
 * идёт дальше, а ЧУЖОЙ перевод он принимает за правду и запоминает. Ни
 * одного морфологического шага (отсечь окончание, привести к
 * начальной форме) здесь поэтому нет и не будет — такой шаг сводит
 * «стали» (глагол) со «сталью», «мой» (местоимение) с «мой» (глагол) и
 * так далее, и отличить эти случаи без разбора предложения нечем.
 *
 * Складывается ровно три вещи, и каждая — не смысл, а запись:
 *
 *  1. РЕГИСТР. «Снегурочка» в начале предложения и «снегурочка» в
 *     середине — одно слово. Тот же обмен уже сделан в
 *     `story-word-pick.ts` для клипов озвучки.
 *  2. ЗНАК УДАРЕНИЯ (U+0301) и прочие комбинируемые надстрочные. В
 *     текстах рассказов они встречаются, в банке — нет.
 *  3. НЕВИДИМЫЕ РАЗДЕЛИТЕЛИ — мягкий перенос, нулевой пробел, BOM.
 *     Человек их не видит, а сличение строк видит.
 *
 * А вот `ё` и `е` НЕ складываются, и это решение, а не недосмотр:
 * «всё» и «все» — РАЗНЫЕ слова с разными переводами (`todo` и `todos`),
 * и сложив их, мы получили бы ровно ту ложную выдачу, ради недопущения
 * которой всё правило и написано. То же различение принято для клипов
 * («регистр складывается, ё и е — нет», `story-word-pick.ts`).
 */

/** Комбинируемые надстрочные знаки (U+0300…U+036F) — среди них ударение. */
const COMBINING_MARKS = /[\u0300-\u036F]/gu;
/** Мягкий перенос, нулевые пробелы, соединители, BOM. */
const INVISIBLE = /[\u00AD\u200B-\u200D\uFEFF]/gu;

/**
 * Одно слово целиком: кириллица, возможно через дефис («кто-то»). Та же
 * форма, по которой `StoryText` решает, какой токен делать тапаемым, —
 * и ТОЛЬКО такие ключи попадают в банк: у многословной карточки
 * («образ мышления») перевода ОТДЕЛЬНОГО слова нет, и брать для «образ»
 * испанский перевод целой пары значило бы соврать.
 */
const SINGLE_WORD = /^[а-яёА-ЯЁ]+(?:-[а-яёА-ЯЁ]+)*$/u;

/** Запись слова, по которой оно ищется в банке. Смысл не трогается. */
export function normalizeBankWord(word: string): string {
  return word
    .normalize("NFC")
    .replace(COMBINING_MARKS, "")
    .replace(INVISIBLE, "")
    .trim()
    .toLowerCase();
}

/** Годится ли строка в КЛЮЧ банка: одно кириллическое слово, не фраза. */
export function isSingleRussianWord(word: string): boolean {
  return SINGLE_WORD.test(word);
}

/** Ключ банка для строки контента; `null` — строка в ключи не годится. */
export function bankKey(source: string | null | undefined): string | null {
  if (!source) return null;
  const key = normalizeBankWord(source);
  return key && isSingleRussianWord(key) ? key : null;
}
