/**
 * ⏪ / ⏩ ПО ОДНОЙ ДОРОЖКЕ РАССКАЗА — ЗАХОД 7.255.
 *
 * Видео POCO 01.10 и журнал той минуты: «Снегурочка» (сохранено 67 %) и
 * «Репка» (71 %) — сразу после открытия страницы, до первого «▶», одно
 * нажатие ⏪. Полоска ушла в ноль, «▶» заиграл с первой фразы.
 *
 * Причина: до первого «▶» дорожка стоит на 0 — сохранённое место
 * подставлялось только в «▶». ⏪ считал −15 с от нуля, а перемотка на 0
 * делала строку 0 текущей и перезаписывала сохранённое место.
 *
 * Правило: пока место не подставлено (`pendingResume` — начало
 * сохранённой строки), ⏪/⏩ считают от НЕГО; иначе — от того, где
 * дорожка. Итог — в пределах [0, длина]. Чистая функция без DOM: её гоняют
 * юнит-тест и сторож R10 `check:story-player-truth` (прямо этот файл).
 */
export function skipTarget(currentTime: number, pendingResume: number | null, delta: number, duration: number): number {
  const from = pendingResume ?? currentTime;
  const end = Number.isFinite(duration) && duration > 0 ? duration : Infinity;
  return Math.min(Math.max(0, from + delta), end);
}
