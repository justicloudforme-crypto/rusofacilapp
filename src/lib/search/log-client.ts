import type { LoggedLang } from "./demand";

/**
 * Отправка одной записи спроса из браузера.
 *
 * `sendBeacon`, а не `fetch`, потому что запись уходит ровно в тот момент,
 * когда окно поиска закрывается — а закрытие чаще всего происходит вместе
 * с переходом по ссылке, то есть страница в эту же миллисекунду начинает
 * уезжать. Обычный `fetch` в такой момент браузер имеет право отменить, и
 * тогда журнал систематически терял бы именно те заходы, у которых был
 * переход, — то есть врал бы в одну сторону про самое интересное поле.
 * `keepalive` у fetch — запасной путь для окружений без `sendBeacon`.
 *
 * Ошибки проглатываются намеренно и молча: человек, закрывший поиск, не
 * должен увидеть ничего от того, что счётчик не сработал.
 */
export function logSearchDemand(payload: {
  query: string;
  resultCount: number;
  lang: LoggedLang;
  followed: boolean;
}): void {
  if (typeof navigator === "undefined") return;
  if (!payload.query.trim()) return;

  const body = JSON.stringify(payload);
  try {
    // `sendBeacon` возвращает БУЛЕВО, и это не украшение: браузер отвечает
    // `false`, когда отказался ставить отправку в очередь — переполнен
    // бюджет, запрещён тип тела, выключен фоновый обмен. Прежняя редакция
    // возвращала управление, не посмотрев на ответ, поэтому «поставили в
    // очередь» и «молча потеряли» выглядели одинаково. Ложь была бы
    // односторонней ровно там, где она дороже всего: отказ вероятнее при
    // уходе со страницы, то есть у тех самых заходов, ради которых журнал
    // и переставал зависеть от способа выхода.
    // Тело — СТРОКА, а не `Blob` с типом `application/json`, и это не
    // мелочь оформления. Строка уезжает как `text/plain;charset=UTF-8` —
    // единственный тип тела, который спецификация Beacon разрешает
    // безусловно; `application/json` в маячке относится к типам, которые
    // браузер вправе отклонить, и тогда единственным следом отказа был бы
    // `false` из функции. Маршрут при этом не меняется вовсе: он читает
    // тело через `request.json()`, которому заголовок типа безразличен.
    //
    // Побочная польза, без которой заход не состоялся бы: тело `Blob`
    // невидимо сетевым средствам — замерено, `postData()` и
    // `postDataBuffer()` у маячка с `Blob` пусты в ОБОИХ движках, — и
    // доказать «на каждом выходе уходит ровно одна запись, и вот с каким
    // содержимым» было бы нечем.
    if (typeof navigator.sendBeacon === "function") {
      const queued = navigator.sendBeacon("/api/search/log", body);
      if (queued) return;
    }
    void fetch("/api/search/log", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body,
      keepalive: true,
    }).catch(() => {});
  } catch {
    // см. комментарий выше
  }
}
