/**
 * Разделы поиска и форма одной записи индекса.
 *
 * Раздел — это не украшение выдачи, а единица, за которую отвечает
 * сторож: `check:search-coverage` требует, чтобы КАЖДЫЙ из них отдавал
 * живой объект. До 05.09.2026 поиск покрывал 0 из 13 разделов сайта
 * (PROGRESS.md 7.127), и молча он это делал именно потому, что «раздел»
 * нигде не был назван списком.
 */
export const SEARCH_SECTIONS = [
  "lesson",
  "exam",
  "story",
  "media",
  "flashcard",
  "vocabularyTopic",
  "idiom",
  "glossary",
  "grammar",
  "alphabet",
  "page",
  "game",
] as const;

export type SearchSection = (typeof SEARCH_SECTIONS)[number];

/**
 * Разделы, которые МОГУТ свернуться в одну строку, — но только когда
 * совпадений больше, чем раздел и так печатает (`PER_SECTION_LIMIT`).
 *
 * Числом: игровых пазлов 3277 из 10 720 названных объектов сайта (30,6%),
 * и их названия строятся шаблоном — «Sopa de letras de <тема> en ruso
 * (<уровень>)». Запрос «sopa de letras» совпадает почти с каждым из них,
 * то есть без свёртки одна семья объектов вытеснила бы из выдачи все
 * остальные одиннадцать разделов сразу. Свёрнутая строка называет число
 * совпадений и ведёт на подборку.
 *
 * Почему это условие, а не свойство раздела. До 07.09.2026 свёртка была
 * безусловной, и замер на живом проде (PROGRESS.md 7.133) показал цену:
 * полное название ОДНОГО пазла давало 1–2 совпадения — и всё равно одну
 * строку на хаб игр, хотя собственный адрес у пазла есть и лежит в этом же
 * индексе. Раздел, уложившийся в свои пять строк, не вытесняет никого, и
 * прятать от человека найденный им объект незачем. Само условие — в
 * match.ts.
 */
export const COLLAPSED_SECTIONS: readonly SearchSection[] = ["game"];

/** Сколько строк одного раздела печатается. Остальные названы числом
 * («показано N из M»), а не выброшены молча. */
export const PER_SECTION_LIMIT = 5;

/** Потолок на всю выдачу — чтобы двенадцать разделов по пять строк не
 * превращали окно поиска в страницу. */
export const TOTAL_RESULT_LIMIT = 24;

/**
 * Одна запись индекса. Локаль-независимая: проекция на `es`/`ru`
 * происходит в момент запроса, поэтому индекс собирается и кешируется
 * один раз на обе локали, а не дважды.
 */
export interface SearchRecord {
  section: SearchSection;
  /** Уникален внутри раздела. */
  id: string;
  /** Путь БЕЗ префикса локали: `/stories/abc`. */
  path: string;
  /** Путь на `/ru`, когда он отличается (у карточек словаря тематические
   * страницы существуют только по-испански). `null` — записи нет на `/ru`
   * вовсе. */
  pathRu?: string | null;
  /** Существует только под `/es` (лендинги, гиды по грамматике,
   * тематические страницы словаря, страница алфавита). */
  esOnly?: boolean;
  /**
   * Название по умолчанию — то, которое видит испаноговорящий. `titleRu`
   * задаётся ТОЛЬКО когда оно другое.
   *
   * Асимметрия не про уважение к локали, а про размер: у 5771 карточки,
   * 771 идиомы, 325 рассказов и 275 медиа название одно на обе локали
   * (русское слово, русская фраза, русское заглавие), и хранить его
   * дважды — это лишний мегабайт в блобе, который каждые пять минут
   * ездит через Redis.
   */
  title: string;
  titleRu?: string;
  subtitle?: string;
  subtitleRu?: string;
  /**
   * Строки, по которым тоже ищут, но которые не печатаются: русское слово
   * карточки, её транскрипция, русский эквивалент термина глоссария.
   * Локаль-независимы намеренно — испаноговорящий, который учит русский,
   * набирает русское слово на `/es` чаще, чем на `/ru`.
   */
  terms?: string[];
  level?: string;
  /** Что нужно, чтобы объект открылся: `null` — ничего, `"free"` — любая
   * подписка, `"premium"` — план Premium. Считается при сборке индекса из
   * тех же правил, что применяет сама страница (entitlement.ts). */
  requires?: "free" | "premium" | null;
}

/** Одна строка выдачи. */
export interface SearchHit {
  section: SearchSection;
  id: string;
  href: string;
  title: string;
  subtitle?: string;
  /** Закрыт ли объект ДЛЯ ЭТОГО посетителя. Ведёт туда же, куда вёл бы
   * открытый, — на страницу, которая сама покажет пейволл. */
  locked: boolean;
  lockReason?: "free" | "premium";
}

export interface SearchSectionResult {
  section: SearchSection;
  /** Сколько совпало всего. */
  total: number;
  /** Сколько показано (0 у свёрнутых разделов). */
  hits: SearchHit[];
  /** Свёрнутый раздел: строка-ссылка на подборку вместо перечня. */
  collapsed: boolean;
  collapsedHref?: string;
}

export interface SearchResponse {
  query: string;
  /** Сколько объектов совпало всего, по всем разделам. */
  total: number;
  /** Сколько строк реально напечатано. */
  shown: number;
  sections: SearchSectionResult[];
  /** Сработала ли нестрогая ступень (опечатки/падежи). Печатается
   * человеку, чтобы «нашлось не то, что набирал» не выглядело ошибкой. */
  fuzzy: boolean;
}
