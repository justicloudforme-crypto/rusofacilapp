import type { LoggedLang } from "./demand";

/**
 * Один заход в поиск как состояние, а не как обработчик закрытия.
 *
 * **Что было и почему это чинилось.** Журнал спроса (7.128, долг 50)
 * писал строку в одном-единственном месте — в `close()` компонента
 * `GlobalSearch`. То есть запись существовала ровно для тех выходов, у
 * которых `close()` вызывается: Escape, крестик, тап по затемнению и
 * переход по строке выдачи. Всё остальное журнал не видел вовсе:
 *
 *   * человек ушёл на другой адрес с открытым окном (строка браузера,
 *     кнопка «назад», внешняя ссылка, аппаратная «назад» на Android) —
 *     **0 записей**;
 *   * человек закрыл вкладку или всё окно браузера — **0 записей**;
 *   * телефон свернул приложение и система выгрузила вкладку — **0
 *     записей**.
 *
 * Перекос у этого пробела односторонний, и в этом всё дело: «искал,
 * ничего не нашёл и ушёл» — то самое поведение, ради которого журнал
 * заводился, — заканчивается уходом со страницы гораздо чаще, чем
 * аккуратным Escape. Журнал систематически недосчитывал именно нужные
 * заходы.
 *
 * **Что стало.** Запись стала независимой от способа выхода: её отправляет
 * первый же наступивший выход, какой бы он ни был, — включая `pagehide` и
 * `visibilitychange`, которые наступают и при закрытии вкладки, и при уходе
 * на другой адрес. А чтобы «Escape и следом закрытие вкладки» не дали двух
 * строк на один заход, решение «пора писать» вынесено сюда и сделано
 * **однократным**: `flush()` отдаёт запись ровно один раз за открытие окна
 * и `null` при любом следующем вызове.
 *
 * **Почему отдельный модуль, а не пара `useRef` внутри компонента.**
 * Свойство «ровно одна строка на заход» — это то, что заход обязан
 * доказать, а доказывать его в браузере на каждый из четырёх выходов
 * дорого и медленно. Здесь оно проверяется юнит-тестом
 * (`demand-session.test.ts`), а браузер проверяет другое: что каждый из
 * четырёх выходов вообще досюда доходит.
 *
 * **Цена решения, названная прямо.** Первый выход выигрывает. Если человек
 * свернул вкладку (`visibilitychange` → `hidden`), вернулся и дописал
 * строку, второй записи не будет: заход уже закрыт числом, которое было
 * видно в момент сворачивания. Обратный выбор — «переоткрывать заход при
 * возврате» — даёт ровно ту цепочку записей одного посетителя, от которой
 * таблица `SearchQuery` защищена по построению (см. `demand.ts`).
 */
export interface SearchDemandDraft {
  query: string;
  resultCount: number;
  lang: LoggedLang;
  followed: boolean;
}

export class SearchDemandSession {
  private draft: SearchDemandDraft | null = null;

  /** Открывает новый заход. Всё, что не было отправлено прежним заходом,
   * теряется намеренно: `open()` зовётся при открытии окна, а окно,
   * открытое второй раз, — это второй заход, а не продолжение первого. */
  open(lang: LoggedLang): void {
    this.draft = { query: "", resultCount: 0, lang, followed: false };
  }

  /** Строка и число найденного на текущий момент. Зовётся при каждом
   * изменении выдачи; последнее значение и есть то, что человек видел,
   * когда уходил. */
  update(patch: Partial<SearchDemandDraft>): void {
    if (this.draft) Object.assign(this.draft, patch);
  }

  /** Человек ушёл по строке выдачи. Ставится ДО `flush()`, потому что
   * переход и есть выход: второго шанса записать это не будет. */
  markFollowed(): void {
    if (this.draft) this.draft.followed = true;
  }

  /** Есть ли что отправлять. Нужно вызывающему, чтобы не заводить
   * обработчики выхода на закрытом окне. */
  get pending(): boolean {
    return this.draft !== null;
  }

  /**
   * Запись, которую надо отправить, — **ровно один раз за открытие окна**.
   * Любой следующий вызов до нового `open()` отдаёт `null`, и именно это
   * не даёт «Escape, а следом закрытие вкладки» превратиться в две строки
   * об одном заходе.
   */
  flush(): SearchDemandDraft | null {
    const draft = this.draft;
    this.draft = null;
    return draft;
  }
}
