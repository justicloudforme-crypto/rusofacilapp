/** Верхняя граница длины адреса по RFC 5321. */
export const MAX_LOGIN_EMAIL_LENGTH = 254;

/**
 * Знаки, которых в адресе быть не может — перечислением и кодами, а не
 * диапазоном в классе символов.
 *
 * Это правило 4.4 из PROGRESS.md в действии: класс вида `[ - <]` читается
 * как ДИАПАЗОН от пробела до `<` и молча отвергает точку, цифры и плюс,
 * то есть почти любой настоящий адрес. Отказ был бы невидимым — поле
 * просто осталось бы пустым, как до правки.
 */
const FORBIDDEN_CHARS = new Set([" ", "<", ">", '"', "'", "`", "\\"]);

function hasForbidden(value: string): boolean {
  for (const char of value) {
    if (FORBIDDEN_CHARS.has(char)) return true;
    const code = char.codePointAt(0) ?? 0;
    // Управляющие знаки любой формы, включая невидимые и перевод строки.
    if (code < 0x20 || code === 0x7f) return true;
  }
  return false;
}

/**
 * Адрес, который не стыдно вернуть в форму, или `null`.
 *
 * `null` — поле останется пустым; это и есть безопасное поведение по
 * умолчанию, то самое, что было до правки.
 */
export function loginRetryEmail(raw: unknown): string | null {
  if (typeof raw !== "string") return null;
  const value = raw.trim();
  if (!value || value.length > MAX_LOGIN_EMAIL_LENGTH) return null;
  if (hasForbidden(value)) return null;
  const parts = value.split("@");
  if (parts.length !== 2) return null;
  const [local, domain] = parts;
  if (!local || !domain || !domain.includes(".")) return null;
  return value;
}
