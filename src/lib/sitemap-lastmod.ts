/**
 * Одно место, где решается, есть ли у URL честная дата — и какая.
 *
 * Зачем отдельный модуль. До 05.09.2026 `<lastmod>` в карте сайта имели
 * 389 URL из 1912: словарь (238), пазлы (148) и три страницы-источника
 * бесплатного индекса (3). У остальных 1523 поля не было, причём по двум
 * РАЗНЫМ причинам, которые в коде выглядели одинаково — «поля нет»:
 *
 *   1. источника даты нет вовсе (медиа: каталог лежит в JSON-файле рядом
 *      с кодом и даты на запись не имеет);
 *   2. источник есть и не читался (рассказы, уроки, страницы категорий).
 *
 * Первое — правильное молчание, второе — потеря. Разделить их можно
 * только назвав источник поимённо, поэтому дата больше нигде не
 * собирается по месту: вызывающий передаёт строки, а решение «дата или
 * молчание» принимается здесь.
 *
 * Правило, унаследованное от sitemap.ts и не меняющееся: выдуманная дата
 * ХУЖЕ молчания. Недостоверный `lastmod` краулер игнорирует не у одного
 * URL, а у всей карты, так что дата сборки, `new Date()` и «сегодня» тут
 * невозможны по построению — ни одна функция ниже не умеет получить
 * текущее время.
 */

/** Строка базы, у которой могут быть обе отметки времени. */
export interface DatedRow {
  updatedAt?: Date | null;
  createdAt?: Date | null;
}

/**
 * Дата последнего изменения строки: `updatedAt`, а если его нет —
 * `createdAt`.
 *
 * Почему `createdAt` — это НЕ выдуманная дата. `WordGamePuzzle.updatedAt`
 * появился в схеме 29.08.2026 (коммит `3e4b4cc`) и объявлен nullable
 * именно потому, что строки, написанные раньше, его не имеют. Замер по
 * банку: у КАЖДОЙ строки с непустым `updatedAt` он не раньше 29.08, а у
 * всех строк с пустым `updatedAt` есть настоящий `createdAt` — то есть
 * пустое поле означает ровно «эту строку с тех пор никто не писал», и
 * последнее её изменение — это и есть её создание.
 *
 * Ошибиться такая замена может только в одну сторону: если строку
 * правили ДО появления колонки, `createdAt` окажется старше настоящей
 * даты правки. Слишком старый `lastmod` не обещает свежести, которой
 * нет, и не стоит ничего; слишком новый — обещает, и стоит доверия ко
 * всей карте. Поэтому падение именно на `createdAt`, а не наоборот.
 */
export function rowLastModified(row: DatedRow): Date | undefined {
  return row.updatedAt ?? row.createdAt ?? undefined;
}

/**
 * Самая поздняя дата среди строк — для страницы, которая эти строки
 * ПЕРЕЧИСЛЯЕТ (каталог, индекс, страница категории).
 *
 * Пустой вход и вход без единой даты дают `undefined`, а не «сегодня»:
 * страница, про которую нечего сказать, обязана промолчать.
 */
export function latestLastModified(rows: Iterable<DatedRow>): Date | undefined {
  let latest: Date | undefined;
  for (const row of rows) {
    const at = rowLastModified(row);
    if (!at) continue;
    if (!latest || at.getTime() > latest.getTime()) latest = at;
  }
  return latest;
}

/**
 * Кусок записи карты сайта: `{ lastModified }` при настоящей дате и
 * ПУСТОЙ объект при её отсутствии.
 *
 * Существует, чтобы у вызывающего не было формы, в которую можно
 * подставить запасную дату: `...lastModifiedField(x)` либо пишет поле,
 * либо не пишет ничего, и третьего варианта в тексте нет.
 */
export function lastModifiedField(at: Date | undefined): { lastModified?: Date } {
  return at ? { lastModified: at } : {};
}
