export interface VocabularyItem {
  word: string;
  transcription: string;
  translation: string;
}

export interface GrammarExample {
  russian: string;
  translation: string;
}

export interface AlphabetLetter {
  letter: string;
  name: string;
  transcription: string;
  type: "vowel" | "consonant" | "sign";
  pronunciation: string;
}

export interface ReadingPracticeItem {
  text: string;
  translation?: string;
}

export interface MultipleChoiceExercise {
  id: string;
  type: "multiple-choice";
  prompt: string;
  options: string[];
  correctIndex: number;
  /** Why the correct option is correct and what grammar rule applies — shown
   * in the student's detailed mistake review (exam profile breakdown). */
  explanation?: string;
}

export interface FillBlankExercise {
  id: string;
  type: "fill-blank";
  before: string;
  after: string;
  answers: string[];
  explanation?: string;
}

export interface MatchingExercise {
  id: string;
  type: "matching";
  pairs: { left: string; right: string }[];
  explanation?: string;
}

/** Student reorders the given words (shown shuffled) into `words`' order. */
export interface WordReorderExercise {
  id: string;
  type: "word-reorder";
  prompt: string;
  words: string[];
  translation?: string;
  explanation?: string;
}

/** Text-to-speech reads `audioText` aloud; student picks the matching option. */
export interface ListeningExercise {
  id: string;
  type: "listening";
  audioText: string;
  prompt: string;
  options: string[];
  correctIndex: number;
  explanation?: string;
}

export interface ReadingQuestion {
  prompt: string;
  options: string[];
  correctIndex: number;
  explanation?: string;
}

export interface ReadingComprehensionExercise {
  id: string;
  type: "reading-comprehension";
  text: string;
  questions: ReadingQuestion[];
}

/** Text-to-speech reads `audioText` aloud; student types what they understood.
 * Graded leniently: trimmed, lowercased, accents ignored, matched against
 * any of `acceptedAnswers`. */
export interface ListeningTranscriptionExercise {
  id: string;
  type: "listening-transcription";
  audioText: string;
  prompt: string;
  acceptedAnswers: string[];
  explanation?: string;
}

export type Exercise =
  | MultipleChoiceExercise
  | FillBlankExercise
  | MatchingExercise
  | WordReorderExercise
  | ListeningExercise
  | ReadingComprehensionExercise
  | ListeningTranscriptionExercise;

