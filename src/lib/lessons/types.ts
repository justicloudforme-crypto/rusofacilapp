/** A Russian letter/word/phrase shown with a speaker button right on the
 * slide, so pronunciation is one tap away without switching tabs. */
export interface SlideAudioExample {
  /** What's spoken aloud (browser TTS) and shown large. */
  text: string;
  /** Short caption under the text — transcription, translation, or both. */
  caption?: string;
}

export interface Slide {
  id: string;
  icon: SlideIconKey;
  title: string;
  body: string[];
  /** Optional short bullet list, rendered under `body`. */
  highlights?: string[];
  /** Optional row of tap-to-listen chips — letters/words relevant to this
   * slide, each with a speaker button. Not audio files: reuses the same
   * browser text-to-speech as SpeakButton elsewhere in the lesson. */
  audioExamples?: SlideAudioExample[];
}

export interface LessonContent {
  /** Optional YouTube or direct HTML5 video URL, shown at the top of the lesson. */
  videoUrl?: string;
  /** Shows the microphone-based pronunciation practice block in the exercises tab. Defaults to true when omitted, so existing lessons keep working unchanged. */
  enableAudioRecording?: boolean;
  grammar: {
    title: string;
    paragraphs: string[];
    /** Short Russian phrase examples with translation, each with a speak button. */
    examples?: GrammarExample[];
  };
  /** Only populated on Lesson 1: the full 33-letter Cyrillic alphabet. */
  alphabet?: AlphabetLetter[];
  /** Presentation deck ("Presentación" tab), downloadable as PDF. */
  slides?: Slide[];
  /** "Práctica de lectura" block: simple words/sentences with speak buttons. */
  readingPractice?: {
    title: string;
    items: ReadingPracticeItem[];
  };
  vocabulary: VocabularyItem[];
  exercises: Exercise[];
}
