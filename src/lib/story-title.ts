import type { Locale } from "@/i18n/config";
import { isFrozenStory } from "@/lib/story-pilot";

/**
 * Как называется рассказ для того, кто на него смотрит.
 *
 * ЗАЧЕМ. Сайт сделан для испаноговорящих, которые русского ещё не знают.
 * До этой правки название рассказа было одной колонкой на обе локали —
 * по-русски, — и это ровно тот же дефект, что уже разобран у подписи
 * автора (см. story-author.ts: «Por Русская народная сказка» на испанской
 * карточке). Разница в цене: подпись — это украшение карточки, а
 * название — единственное, по чему читатель выбирает, что открыть.
 * Испаноговорящий не может догадаться, о чём «День стирки», и каталог из
 * 325 таких строк для него — не каталог.
 *
 * ПРАВИЛО, и оно здесь одно на весь сайт:
 *
 *   - на `/es`, когда у рассказа есть `titleEs`, — испанское название
 *     ПЕРВОЙ строкой, русский оригинал ВТОРОЙ и мельче. Второе не
 *     украшение: русское название — это оригинал изучаемого языка, и
 *     прятать его от ученика значит отнимать у него половину смысла
 *     страницы;
 *   - `titleEs` пуст → печатается ровно то, что печаталось до появления
 *     колонки, знак в знак: `primary = title`, `secondary = null`;
 *   - `/ru` не меняется вовсе. Там русское название И ЕСТЬ название, а
 *     «Día de colada» под ним — та же половинчатая подача, только
 *     повёрнутая другой стороной.
 *
 * ЗАМОРОЗКА. 65 рассказов A1 (50 пилот + 15 контроль) участвуют в замере
 * «тело тонким страницам» до 25.09.2026, и правило заморозки требует, чтобы
 * у них не менялось НИЧЕГО — ни `<title>`, ни `<h1>`, ни то, что видно на
 * карточке. Поэтому новая подача до них не доходит, даже когда `titleEs` у
 * них уже записан: ветка ниже отдаёт им ровно старый вид. Ключ — та же пара
 * `(title, level)`, которой заморозка пользуется везде (`isFrozenStory`), а
 * не `id`: идентификаторы расходятся между локальной копией и Turso, и
 * список по `id` молча указывал бы на чужие строки.
 *
 * Значит, у правила есть свойство, которое и делает PR кода безопасным:
 * **на пустых данных `storyTitles` тождественно старому коду.** Ни один
 * заголовок не сдвигается, пока в `titleEs` не появится текст.
 */
export interface StoryTitleRow {
  title: string;
  titleEs?: string | null;
  level: string;
}

export interface StoryTitleView {
  /** Крупная строка — то, что читатель видит как название. */
  primary: string;
  /** Мелкая строка под ней, или `null`, когда второй строки нет вовсе. */
  secondary: string | null;
}

/** Пустая строка и строка из одних пробелов — это «названия нет», а не
 * название. Иначе случайно сохранённый пробел выключил бы русский
 * оригинал и оставил читателя без обеих строк. */
function cleaned(value: string | null | undefined): string | null {
  if (typeof value !== "string") return null;
  const trimmed = value.trim();
  return trimmed ? trimmed : null;
}

export function storyTitles(story: StoryTitleRow, lang: Locale): StoryTitleView {
  if (lang !== "es") return { primary: story.title, secondary: null };
  if (isFrozenStory(story)) return { primary: story.title, secondary: null };
  const es = cleaned(story.titleEs);
  if (!es) return { primary: story.title, secondary: null };
  return { primary: es, secondary: story.title };
}

/** Строки, по которым этот рассказ должен находиться поиском, независимо
 * от локали: и русское название, и испанское. Испаноговорящий, который
 * учит русский, набирает русское слово на `/es` чаще, чем на `/ru` (см.
 * `terms` в src/lib/search/types.ts). */
export function storySearchTerms(story: StoryTitleRow): string[] {
  const es = cleaned(story.titleEs);
  return es ? [story.title, es] : [story.title];
}

const CYRILLIC = /\p{Script=Cyrillic}/u;

/**
 * Правило сторожа `npm run check:story-title-es`, вынесенное сюда, чтобы
 * его можно было прогнать по подсаженной выборке и по живой базе ОДНИМ И
 * ТЕМ ЖЕ кодом.
 *
 * Кириллица в испанском названии — это не «немного русского», а признак
 * того, что поле заполнено не тем: либо туда попал русский оригинал
 * целиком, либо перевод остановился на полуслове. Половина перевода хуже,
 * чем его отсутствие — то же правило, что у `localizeStoryAuthor`.
 */
export function spanishTitleProblem(titleEs: string): string | null {
  const trimmed = titleEs.trim();
  if (!trimmed) return "пустая строка — это не «нет названия», а запись пустоты; поле должно быть NULL";
  if (CYRILLIC.test(trimmed)) return "кириллица в испанском названии";
  return null;
}
