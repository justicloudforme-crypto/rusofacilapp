/**
 * ПОЛЯ ЗАПИСИ ОЧЕРЕДИ БЕЗ СЕТИ — ЗАХОД 7.236 (ОФЛАЙН-3б).
 *
 * Ответ урока, данный без сети, ждёт в очереди браузера
 * (`src/lib/progress-outbox.ts`) и уходит на `POST /api/progress`, когда
 * сеть вернётся. Три поля делают из «ещё одной отправки» запись, которую
 * сервер примет ровно один раз и засчитает правильным днём:
 *
 *   `key`   — ключ записи (UUID браузера). Повтор того же ключа — пустая
 *             операция: без второй попытки и без второго дня занятия.
 *             Замер 7.236 до правки: сервер обработал одну попытку ДВАЖДЫ.
 *   `at`    — когда ученик нажал «Comprobar». День занятия ставится ЗА
 *             ДЕЙСТВИЕ (7.204) — значит по времени действия, а не
 *             отправки: иначе ответ из самолёта в воскресенье, ушедший в
 *             понедельник, отметил бы понедельник.
 *   `owner` — чья запись (`ownerScope`, соль-хеш id, 7.49). Сервер
 *             сличает его с сессией и чужую запись НЕ принимает. Замер
 *             7.236 до правки: попытка аккаунта A после выхода и входа B
 *             легла под B.
 *
 * Модуль чистый — ни базы, ни запроса, — чтобы правила читались и
 * проверялись примерами (`offline-record.test.ts`).
 */

/** Насколько назад сервер верит времени действия. Дольше неделя без сети —
 *  редкость, а шире окно — шире лазейка «нарисовать себе серию задним
 *  числом» (день занятия виден в серии и значках). Старше — день ставится
 *  по времени приёма, сама попытка при этом всё равно записывается. */
export const MAX_ACTION_AGE_MS = 7 * 24 * 60 * 60 * 1000;

const KEY_SHAPE = /^[A-Za-z0-9_-]{16,64}$/;

/** Ключ записи или `null`, если его нет или он не похож на ключ. */
export function parseRecordKey(value: unknown): string | null {
  return typeof value === "string" && KEY_SHAPE.test(value) ? value : null;
}

/**
 * Момент действия, которому сервер готов поверить. Без ключа — всегда
 * «сейчас»: время действия имеет смысл только у записи очереди.
 */
export function actionInstant(value: unknown, hasKey: boolean, now: Date = new Date()): Date {
  if (!hasKey || typeof value !== "number" || !Number.isFinite(value)) return now;
  const at = Math.round(value);
  // Часы телефона впереди сервера — действие случилось «сейчас».
  if (at > now.getTime()) return now;
  if (now.getTime() - at > MAX_ACTION_AGE_MS) return now;
  return new Date(at);
}

/** Запись чужая, если владелец указан и не совпадает с владельцем сессии. */
export function isForeignRecord(owner: unknown, sessionOwner: string): boolean {
  return typeof owner === "string" && owner.length > 0 && owner !== sessionOwner;
}
