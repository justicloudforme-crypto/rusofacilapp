/**
 * СКОЛЬКО ЧЕГО ВОРКЕР ДЕРЖИТ НА УСТРОЙСТВЕ — ДОЛГИ 75, 76 И 77.
 *
 * Три строки таблицы долгов — про один и тот же воркер, и чинятся они
 * одной правкой: у каждого вида содержимого появляется СВОЙ кеш со СВОИМ
 * объявленным потолком, и потолок этот объявлен здесь — в одном месте,
 * которое читают и сам воркер, и сторож, и живая проба.
 *
 * ДОЛГ 75 дословно: «`rf-pages-rsc-prefetch` держит **139** записей против
 * объявленных 32 и не сжимается: перемерено через 20 секунд и после ещё
 * одной навигации — 139 каждый раз, при том что соседний `others` в том же
 * прогоне стоит ровно на 32, то есть счётчик исправен → разбор → он
 * потребует правки `src/sw.ts`».
 *
 * ДОЛГ 76 дословно: «страничный кэш `others` держит 32 записи, и это ОБЩИЙ
 * счёт документов и статики: в замере среди 32 записей документов было 8, а
 * 24 — `.js`, `.css`, `.woff2` и `/_next/image` → офлайн после обычного
 * пользования → из 12 обойдённых подряд адресов офлайн открылись **8**,
 * четыре отдали `offline.html`, и первыми выпали главная и обе страницы
 * уроков… чинится квотой и разделением счёта, а не механизмом».
 *
 * ДОЛГ 77 дословно: «все клипы лежат на чужом источнике
 * (`*.public.blob.vercel-storage.com`), а маршрут `static-audio-assets`
 * описан регуляркой `\.mp3$`, и `RegExpRoute` в `serwist` отказывается
 * применять регулярку к чужому адресу, если совпадение начинается не с
 * нулевого символа → … запрошено **40** разных клипов, все 40 вернулись
 * 200, в `static-audio-assets` попало **0** (кэш не создан вовсе), в общий
 * `cross-origin` — **32**, а у него потолок 32 записи и **3600 секунд**».
 *
 * ЧТО ИЗМЕНИЛОСЬ ПО СУЩЕСТВУ, И ПОЧЕМУ ИМЕННО ТАК.
 *
 * 1. ДОКУМЕНТЫ ПОЛУЧИЛИ СВОЙ МАРШРУТ. У `defaultCache` маршрут «pages»
 *    недостижим по построению: он требует у ЗАПРОСА заголовок
 *    `Content-Type: text/html`, а навигация его не шлёт никогда (заголовок
 *    описывает тело, а у GET-навигации тела нет) — это замерено и записано
 *    в `sw-cache-names.ts`. Поэтому каждый документ падал в всеохватный
 *    `others` и делил тридцать две записи с `.js`, `.css`, `.woff2` и
 *    `/_next/image`. Наш маршрут судит по `request.mode === "navigate"` —
 *    признаку самой навигации, а не по заголовку, которого не бывает.
 *
 * 0. НАСТОЯЩАЯ ПРИЧИНА ДОЛГА 75 — `Vary`, И НАЙДЕНА ОНА ЭКСПЕРИМЕНТОМ.
 *    Строка долга говорила «причина не установлена», и до 19.09.2026 так и
 *    было. Замер на собранном воркере: после прокрутки трёх каталогов
 *    браузер сделал 689 предзагрузок, а в кеше лежало **704 записи при
 *    объявленных 64** — при том что в хранилище сроков годности
 *    (`IndexedDB serwist-expiration`) на все кеши сразу было 69 записей.
 *    То есть плагин вычёркивал лишнее у себя и звал `cache.delete(url)`, а
 *    из кеша не удалялось ничего: `CacheExpiration` зовёт удаление БЕЗ
 *    `matchOptions`, и браузер обязан учитывать `Vary`. У ответа RSC он
 *    длинный, поэтому один адрес лежит несколькими записями, и ключ без
 *    этих заголовков не совпадает ни с одной. С `ignoreVary: true` тот же
 *    прогон даёт **ровно 64 записи при 689 предзагрузках**. Признак стоит
 *    только на УДАЛЕНИИ: читает кеш стратегия своими правилами, поэтому
 *    чужой flight-ответ никому не отдастся.
 *
 * 2. У КАЖДОГО КЕША СВОЙ `ExpirationPlugin`, СОЗДАННЫЙ ЗДЕСЬ. До правки
 *    переименованные стратегии получали ЧУЖИЕ объекты плагинов — те, что
 *    `@serwist/next` собрал для своих имён кешей. Потолок в 32 записи,
 *    который они несли, был объявлен не нами, и починить его было негде:
 *    он приходил из `node_modules`. Теперь число стоит в этой таблице,
 *    сторож `check:sw-cache-policy` держит его на месте, а живая проба
 *    `e2e/sw-cache-budget.spec.ts` сверяет объявленное с тем, что и правда
 *    лежит на устройстве после обычного пользования.
 *
 * 3. КЛИПЫ ОЗВУЧКИ СУДЯТСЯ ФУНКЦИЕЙ, А НЕ РЕГУЛЯРКОЙ. Причина долга 77 —
 *    не в потолке, а в том, что маршрут не срабатывал ВОВСЕ: `RegExpRoute`
 *    у `serwist` отказывается применять регулярку к чужому адресу, когда
 *    совпадение начинается не с нулевого символа, а `\.mp3$` на адресе
 *    вида `https://…blob.vercel-storage.com/a/b.mp3` совпадает в конце.
 *    Функция такого ограничения не имеет по построению.
 */

/** Сутки и тридцать суток — в секундах, как их ждёт `ExpirationPlugin`. */
const DAY = 24 * 60 * 60;
const MONTH = 30 * DAY;

export interface CacheBudget {
  /** Имя кеша без отпечатка сборки (полное собирает `pageCacheNames`). */
  key: "html" | "rsc" | "rscPrefetch" | "others" | "content" | "audio";
  /** Сколько записей кеш держит. Число объявлено ЗДЕСЬ, а не в чужом пакете. */
  maxEntries: number;
  /** Сколько живёт запись. */
  maxAgeSeconds: number;
  /** Зачем именно столько — словами, не «на глаз». */
  why: string;
}

