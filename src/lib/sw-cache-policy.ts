/** Имя кеша клипов. Отпечатком сборки НЕ метится намеренно: клип не
 *  меняется от выката, и выбрасывать его на каждый деплой — платить
 *  трафиком человека за нашу сборку. */
export const AUDIO_CACHE_NAME = "rf-audio";

/** Чужой источник, на котором лежат клипы. Проверяется по КОНЦУ имени
 *  хоста, а не подстрокой: `evil-blob.vercel-storage.com.attacker.tld`
 *  подстроку содержит, а концом её не является. */
export const AUDIO_HOST_SUFFIX = ".public.blob.vercel-storage.com";

const AUDIO_EXTENSION = /\.(mp3|wav|ogg|m4a)$/i;

/**
 * Клип ли это озвучки. Функция, а не регулярка, и это и есть починка
 * долга 77: `RegExpRoute` не применяет регулярку к чужому адресу, если
 * совпадение начинается не с нулевого символа.
 */
export function isAudioClipUrl(url: URL): boolean {
  if (!AUDIO_EXTENSION.test(url.pathname)) return false;
  // Чужой источник — боевой банк клипов; свой путь `/audio/…` — локальный
  // кеш генерации (`public/audio`, в репозиторий не входит и на проде не
  // читается). Оба — клипы, и правило у них одно.
  return url.hostname.endsWith(AUDIO_HOST_SUFFIX) || url.pathname.startsWith("/audio/");
}
