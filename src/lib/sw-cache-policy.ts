const CONTENT_PATH = /^\/(es|ru)\/(courses\/[^/]+\/[^/]+|stories\/[^/]+|vocabulary(\/[^/]+)?)\/?$/;

/** Страница ли это, ради которой офлайн-2 вообще делался. */
export function isOfflineContentPath(pathname: string): boolean {
  return CONTENT_PATH.test(pathname);
}

/**
 * ЗАКРЫТОЕ СОДЕРЖАНИЕ НА УСТРОЙСТВЕ НЕ ОСТАЁТСЯ — ЗАХОД 7.229.
 *
 * Признак берётся не из нашего воображения, а из разметки, которую
 * страница и так печатает для поисковика: `paywallJsonLd`
 * (`src/lib/site.ts`) ставит `isAccessibleForFree: false` ровно тогда,
 * когда ЭТОМУ посетителю закрытая часть не отдана. Урок, рассказ и
 * медиа-страница печатают её все три.
 *
 * Правило одно и работает в обе стороны:
 *   * доступа нет → копия НЕ кладётся (в том числе у вышедшего и у
 *     гостя — им закрытую часть и не отдали);
 *   * доступа больше нет (подписка кончилась) → при первом же заходе с
 *     сетью сервер печатает тот же признак, и прежняя копия СТИРАЕТСЯ.
 *
 * Второй рубеж — выход из учётной записи: имя кеша начинается с
 * `rf-pages`, а такие кеши кнопка выхода стирает целиком
 * (`personalPageCaches`). Один рубеж здесь был бы слишком: у общего
 * телефона цена ошибки — чужой платный урок.
 */
const CLOSED_MARKER = '"isAccessibleForFree":false';

export function looksClosedForThisVisitor(html: string): boolean {
  return html.includes(CLOSED_MARKER);
}

