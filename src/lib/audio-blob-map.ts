/**
 * ПРАВИЛО ПРОДОЛЖЕНИЯ ПЕРЕНОСА ОЗВУЧКИ В BLOB — ОДНО ОПРЕДЕЛЕНИЕ.
 *
 * Вынесено из `prisma/migrate-audio-to-blob.ts` 19.09.2026 (заход 7.216)
 * по той же причине, что и `free-trial-limits.ts`: правило должно
 * читаться тестом, а сам скрипт тянет Prisma, `dotenv` и адаптер
 * better-sqlite3, которых тесту не нужно и которым запрещено появляться
 * в прогоне (`check:no-db-in-tests`).
 *
 * ДОЛГ 38: ПРОДОЛЖЕНИЕ СЧИТАЛО «УЖЕ ПЕРЕНЕСЕНО» ПО КЛЮЧУ, А `audioUrl`
 * К ТОМУ МОМЕНТУ УЖЕ ЗНАЧЕНИЕ.
 *
 * Строка долга дословно: «`migrate-audio-to-blob.ts` пропускает строку по
 * `map[row.audioUrl]`, но ключи карты — старые публичные пути, а
 * `audioUrl` после `apply-audio-blob-urls` уже URL Blob: ключ и значение
 * поменялись местами → любой запуск `migrate:audio-to-blob`, включая
 * `--dry-run` (признак: «0 already migrated» при 21 866 записях в карте)
 * → холостой прогон врёт числом, боевой перезальёт весь стор (~1,9 ГБ);
 * чинить сравнением по значению».
 *
 * Карта — это `старый публичный путь -> URL Blob`. После того как
 * `apply-audio-blob-urls` переписал колонку, у КАЖДОЙ строки в базе
 * `audioUrl` равен ЗНАЧЕНИЮ карты, а ключей там больше нет вовсе.
 * Поэтому `!map[row.audioUrl]` было истинно у всех 21 866 строк: очередь
 * = вся база, «0 already migrated», и боевой прогон залил бы стор
 * заново — 1,9 ГБ чужих операций за то, что уже лежит на месте.
 *
 * Правило теперь спрашивает обе стороны карты: строка перенесена, если её
 * `audioUrl` стоит в карте КЛЮЧОМ (перенос был, колонку ещё не
 * переписывали) ИЛИ ЗНАЧЕНИЕМ (перенос был и колонку уже переписали).
 * Отдельная чистая функция, а не выражение на месте: её проверяет
 * `src/lib/audio-blob-map.test.ts`, и там же позитивным контролем
 * прогоняется СТАРОЕ правило — оно обязано называть перенесённую строку
 * неперенесённой, иначе тест ничего не доказывает.
 */
export function isAlreadyMigrated(audioUrl: string, map: Record<string, string>, migratedValues?: Set<string>): boolean {
  if (map[audioUrl]) return true;
  return (migratedValues ?? new Set(Object.values(map))).has(audioUrl);
}
