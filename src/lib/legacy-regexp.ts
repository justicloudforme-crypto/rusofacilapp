/**
 * ДВИЖОК БЕЗ ПРОСМОТРА НАЗАД — СТЕНД, А НЕ МНЕНИЕ.
 *
 * Зачем он нужен. Утверждение «это выражение соберётся в Safari 15»
 * нечем проверить на машине, где стоит V8 2026 года: V8 просмотр назад
 * умеет и молча принимает всё, что мы ему дадим. Поэтому утверждение
 * либо остаётся честным словом, либо ему заводится стенд. Здесь стенд.
 *
 * ЧТО ИМЕННО ЭМУЛИРУЕТСЯ, И ПОЧЕМУ ЭТОГО ДОСТАТОЧНО. Движок, не знающий
 * ES2018-просмотра назад, спотыкается на нём НА РАЗБОРЕ: `(?<` он
 * читает как открывающую группу, за которой идёт недопустимый символ, и
 * бросает `SyntaxError` ещё до первого сопоставления. То есть разница
 * между «старый движок» и «новый» на этом месте — ровно одна: принять
 * ли последовательность `(?<=` / `(?<!`.
 *
 * ИМЕНОВАННАЯ ГРУППА `(?<имя>…)` СЮДА НЕ ВХОДИТ, И ЭТО РЕШЕНИЕ ПО
 * ЗАМЕРУ, А НЕ НЕДОСМОТР. Она тоже ES2018, но появилась в Safari 11.1
 * (2018) — на пять лет раньше просмотра назад (16.4, 2023), и ровно
 * поэтому граница у них разная. В `src/lib/exams/localize.ts`
 * именованные группы стоят и сегодня; объявить их отказом значило бы
 * покрасить сторож там, где ни один живой движок не спотыкается.
 *
 * Отсюда форма стенда: он читает исходник выражения так же, как читал
 * бы старый разборщик, — посимвольно, помня, экранирован ли символ и
 * находимся ли мы внутри класса `[...]`, — и на первой же такой
 * последовательности бросает `SyntaxError` с тем же смыслом, что бросил
 * бы браузер. Всё остальное отдаётся настоящему `RegExp`, потому что
 * всё остальное движки понимают одинаково.
 *
 * Чего стенд НЕ делает и на что не претендует: он не эмулирует
 * сопоставление, не знает про `v`-флаг и не судит про `\p{…}` (оно
 * старше просмотра назад на пять лет, см. `glossary-pattern.ts`). Это
 * прибор на один вопрос: соберётся ли выражение там, где просмотра
 * назад нет.
 */

/** Ошибка ровно того класса, что бросил бы браузер без просмотра назад. */
export class LegacyRegExpSyntaxError extends SyntaxError {
  constructor(feature: string, source: string) {
    super(
      `Invalid regular expression: /${source}/: движок без ES2018 не знает «${feature}» ` +
        `— выражение не собирается вовсе (Safari до 16.4, Chrome до 62)`,
    );
    this.name = "SyntaxError";
  }
}

/**
 * Находит первую последовательность `(?<`, которая в старом движке
 * фатальна. Возвращает её («(?<=», «(?<!» или «(?<имя>») или `null`.
 *
 * Читает посимвольно, а не `indexOf("(?<")`: `\(?<` — это литеральная
 * скобка, а `[(?<]` — класс из трёх символов, и ни то ни другое старый
 * движок не смущает. Поиск подстрокой объявил бы их отказом и
 * превратил бы сторож в источник ложных красных.
 */
export function findLookbehind(source: string): string | null {
  let escaped = false;
  let inClass = false;
  for (let i = 0; i < source.length; i += 1) {
    const char = source[i];
    if (escaped) {
      escaped = false;
      continue;
    }
    if (char === "\\") {
      escaped = true;
      continue;
    }
    if (inClass) {
      if (char === "]") inClass = false;
      continue;
    }
    if (char === "[") {
      inClass = true;
      continue;
    }
    if (char === "(" && source[i + 1] === "?" && source[i + 2] === "<") {
      const kind = source[i + 3];
      if (kind === "=" || kind === "!") return `(?<${kind}`;
    }
  }
  return null;
}

/**
 * Собирает выражение так, как собрал бы движок без ES2018-просмотра
 * назад: бросает `SyntaxError`, если просмотр назад в исходнике есть, и
 * отдаёт настоящий `RegExp`, если нет.
 */
export function compileWithoutLookbehind(source: string, flags = ""): RegExp {
  const found = findLookbehind(source);
  if (found) throw new LegacyRegExpSyntaxError(found, source);
  return new RegExp(source, flags);
}
