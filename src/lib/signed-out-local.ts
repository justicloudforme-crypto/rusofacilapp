/** Приставки ключей, у которых хвост переменный. */
export const PERSONAL_LOCAL_PREFIXES = [
  // `lesson-passed:<уровень>:<урок>` — пройденные уроки.
  "lesson-passed:",
  // `rf-welcome-shown:<userId>:<день>` — несёт в себе ИДЕНТИФИКАТОР
  // человека, и после выхода это чужая запись по построению.
  "rf-welcome-shown:",
];

/**
 * Ключи, которые остаются НАМЕРЕННО. Список нужен не для кода, а для
 * следующего читателя: «не удалили» здесь — решение, а не пропуск.
 *
 *   `rusofacil-sound-enabled`      — звук включён или выключен на этом
 *                                    устройстве. Настройка железа, не
 *                                    человека.
 *   `rusofasil:glossary-discovered` — «этот человек уже понял, что
 *                                    подчёркнутые термины нажимаются».
 *                                    Разовая подсказка интерфейса; она не
 *                                    говорит, ЧЕМ он занимался.
 */
export const KEPT_LOCAL_KEYS = ["rusofacil-sound-enabled", "rusofasil:glossary-discovered"];

/**
 * Какие из ЖИВЫХ ключей хранилища подлежат уборке. Список берётся у
 * самого хранилища, а не собирается по памяти: у ключей с приставкой
 * хвост знать неоткуда.
 */
export function personalLocalKeys(existing: readonly string[]): string[] {
  return existing.filter(
    (key) => PERSONAL_LOCAL_KEYS.includes(key) || PERSONAL_LOCAL_PREFIXES.some((p) => key.startsWith(p)),
  );
}
