  // Карточки: отметка «знаю» и коробки повторения.
  "rusofacil:flashcard-progress",
  "rusofacil:flashcard-srs",
  // Рассказы: страница, на которой человек остановился, и процент.
  "rusofacil:story-progress",
  // Неотправленные результаты уроков.
  "rusofasil:pending-progress",
