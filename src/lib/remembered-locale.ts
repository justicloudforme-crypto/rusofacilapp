export const LOCALE_COOKIE = "rf-lang";

/** Год. Выбор языка — не сессия: он обязан пережить и закрытие
 *  приложения, и месяц без него. */
export const LOCALE_COOKIE_MAX_AGE = 60 * 60 * 24 * 365;

/** Локаль из куки, если она годная. Чужое значение читается как «не
 *  запомнено» — список локалей один на проект (`src/i18n/config.ts`). */
export function rememberedLocale(value: string | undefined): Locale | null {
  if (!value || !isLocale(value)) return null;
  return value;
}

/** Локаль первого сегмента пути, если он локаль. */
export function localeOfPath(pathname: string): Locale | null {
  const first = pathname.split("/").filter(Boolean)[0];
  if (!first || !isLocale(first)) return null;
  return first;
}
