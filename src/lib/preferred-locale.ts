import { defaultLocale, isLocale, type Locale } from "@/i18n/config";

/**
 * Язык, которым отвечать посетителю, пришедшему на адрес БЕЗ локали.
 *
 * ДОЛГ 155. Строка долга звучала так: «телефон с третьим языком системы
 * получает не испанский; правка задевает каждый адрес». Замер на живом
 * проде 18.09.2026 (восемь значений `Accept-Language`, GET на `/`,
 * смотрелся заголовок `Location` у 307) ГЛАВНОЕ ОПАСЕНИЕ НЕ ПОДТВЕРДИЛ:
 * `pt-BR`, `en-US`, `de-DE` и запрос вовсе без заголовка уходили на
 * `/es` — четыре из четырёх. Молчаливым ответом и был испанский.
 *
 * Зато тот же замер нашёл настоящую дыру, о которой строка долга не
 * говорила: `en-US,ru;q=0.3,es;q=0.9` отдавал **`/ru`**. Прежний разбор
 * шёл по ПОРЯДКУ перечисления и веса `q` не читал вовсе, а по RFC 9110
 * порядок ничего не значит — значение имеет только `q`. Телефон, у
 * которого испанский стоит вторым по счёту, но первым по весу, получал
 * русский интерфейс: ровно та беда, ради которой долг заводился, только
 * приходила она с другой стороны.
 *
 * ПОЧЕМУ ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ПРАВКА НА МЕСТЕ. Функция жила внутри
 * `src/proxy.ts` приватной и не была накрыта ни одним тестом: ни
 * юнитом, ни пробой. Решение о языке принимается для КАЖДОГО адреса
 * сайта без префикса локали, и проверять его по живому серверу дорого,
 * а не проверять — дороже. Здесь она чистая: вход — строка заголовка,
 * выход — локаль, и её можно спросить таблицей значений.
 *
 * `q=0` означает «этого языка мне не надо» (RFC 9110, 12.5.4) и потому
 * выбрасывается, а не считается весом. Итог по-прежнему никогда не
 * пустой: не нашлось ничего нашего — `defaultLocale`, то есть испанский.
 */
export function preferredLocaleFromHeader(header: string | null | undefined): Locale {
  if (!header) return defaultLocale;

  const weighted: Array<{ tag: string; q: number; order: number }> = [];
  header.split(",").forEach((raw, order) => {
    const [tagPart, ...params] = raw.split(";");
    const tag = tagPart?.trim().toLowerCase();
    if (!tag) return;

    let q = 1;
    for (const param of params) {
      const match = /^\s*q\s*=\s*([0-9]*\.?[0-9]+)\s*$/i.exec(param);
      if (match) {
        const parsed = Number.parseFloat(match[1]);
        if (Number.isFinite(parsed)) q = parsed;
      }
    }
    if (!(q > 0)) return; // «не предлагать» — не то же, что «слабее»
    weighted.push({ tag, q, order });
  });

  // Порядок перечисления остаётся вторым ключом, а не первым: при равных
  // весах он и есть намерение отправителя, и прежнее поведение на
  // обычных заголовках браузера (веса уже убывают) слово в слово то же.
  weighted.sort((a, b) => b.q - a.q || a.order - b.order);

  for (const { tag } of weighted) {
    const short = tag.split("-")[0];
    if (isLocale(short)) return short;
  }

  return defaultLocale;
}
