import "server-only";
import { headers } from "next/headers";

/**
 * Признак того, что страницу открыл НЕ браузер, а нативная оболочка —
 * webview приложения из App Store или Google Play.
 *
 * Зачем это вообще нужно на сервере (долг 79). Оболочка Capacitor здесь
 * не несёт внутри себя сайт: она грузит боевой адрес удалённо
 * (`server.url` в `capacitor.config.ts`), то есть запрашивает ровно те же
 * страницы, что и обычный браузер, и получает ровно тот же HTML. Замер
 * 7.180: `/es/pricing`, запрошенная с User-Agent мобильного Safari,
 * отдавала те же ТРИ формы `action="/api/checkout"`, что и вебу. Внутри
 * приложения такая страница — не «неудобство», а отклонение на ревью:
 * App Store 3.1.1 и Google Play Payments запрещают уводить на внешнюю
 * оплату цифрового содержимого.
 *
 * Развести это на КЛИЕНТЕ (`Capacitor.isNativePlatform()`) недостаточно:
 * клиентская ветка убирает формы из ЖИВОГО DOM после гидрации, но в
 * ответе сервера они остаются, и ровно этот ответ читает и человек с
 * «просмотром исходного кода», и любой автоматический обход. Поэтому
 * признак приходит в запросе: нативная оболочка дописывает к своему
 * User-Agent токен {@link NATIVE_USER_AGENT_TOKEN} (`appendUserAgent` в
 * `capacitor.config.ts`), и сервер решает ДО отрисовки.
 *
 * Обычный браузер этого токена не шлёт никогда, поэтому веб-ответ от
 * появления этой ветки не меняется ни на один байт — и это проверено
 * побайтовым сличением, а не рассуждением (заход 7.183).
 */
// Написание НЕ брендовое и намеренно, по двум причинам сразу. Значение
// User-Agent обязано быть ASCII, а в имени продукта есть «á», и в
// заголовок оно не кладётся; а написать то же имя без диакритики
// запрещает `npm run check:brand` — он ловит это во всём репозитории.
// Поэтому токен чисто технический и с именем продукта не пересекается.
export const NATIVE_USER_AGENT_TOKEN = "RFNativeShell";

/** true, если запрос пришёл из нативной оболочки приложения. */
export async function isNativeShellRequest(): Promise<boolean> {
  const ua = (await headers()).get("user-agent");
  return ua !== null && ua.includes(NATIVE_USER_AGENT_TOKEN);
}
