/**
 * Форма кода доступа: алфавит, нормализация, печать для человека.
 *
 * Отдельным файлом от `src/lib/access-code.ts` ровно по одной причине, и она
 * не про красоту: тот файл помечен `server-only` и не импортируется из
 * скрипта под `tsx` (та же причина, по которой `prisma/grant-subscription.ts`
 * переписывает у себя `MANUAL_GRANT_DAYS`). А нормализация обязана быть ОДНА
 * на записи и на чтении: разойдись они хоть в одном знаке — и выпущенная
 * партия перестанет погашаться, причём молча.
 *
 * PROGRESS.md 7.146.
 */

/**
 * 26 знаков. Убраны все пары, которые путают, переписывая код с бумаги или с
 * экрана телефона: 0/O, 1/I/L, 5/S, 8/B, Z/2. Код читают вслух и вводят
 * руками, поэтому цена одной перепутанной буквы — письмо в поддержку.
 */
export const ACCESS_CODE_ALPHABET = "ACDEFGHJKMNPQRTUVWXY234679";

/**
 * Одна нормализация на всех: и на записи (скрипт выпуска), и на чтении
 * (маршрут погашения).
 *
 * Верхний регистр, выкинуты пробелы и дефисы. Дефисы — потому что код
 * печатается человеку группами (`AMIGO-K7M2-QW9F`), и переписать его без
 * дефисов так же законно, как с ними. Уникальность в базе стоит на уже
 * нормализованном значении, поэтому она настоящая, а не «уникальность с
 * точностью до регистра».
 */
export function normalizeAccessCode(raw: string): string {
  return raw.trim().toUpperCase().replace(/[\s-]+/g, "");
}

/** Как код показывают человеку: приставка, потом группы по четыре. */
export function formatAccessCode(code: string, prefix: string): string {
  const body = code.slice(prefix.length);
  return [prefix, ...(body.match(/.{1,4}/g) ?? [])].join("-");
}
