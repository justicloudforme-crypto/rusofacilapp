/**
 * Форма кода доступа: алфавит, нормализация, печать для человека.
 *
 * Отдельным файлом от `src/lib/access-code.ts` ровно по одной причине, и она
 * не про красоту: тот файл помечен `server-only` и не импортируется из
 * скрипта под `tsx` (та же причина, по которой `prisma/grant-subscription.ts`
 * переписывает у себя `MANUAL_GRANT_DAYS`). А нормализация обязана быть ОДНА
 * на записи и на чтении: разойдись они хоть в одном знаке — и выпущенная
 * партия перестанет погашаться, причём молча.
 *
 * PROGRESS.md 7.146.
 */

/**
 * 26 знаков. Убраны все пары, которые путают, переписывая код с бумаги или с
 * экрана телефона: 0/O, 1/I/L, 5/S, 8/B, Z/2. Код читают вслух и вводят
 * руками, поэтому цена одной перепутанной буквы — письмо в поддержку.
 */
export const ACCESS_CODE_ALPHABET = "ACDEFGHJKMNPQRTUVWXY234679";

/**
 * Знаки, которые выбрасываются из введённой строки.
 *
 * ОТКУДА ЭТОТ СПИСОК, а не «пробел и дефис». 08.09.2026 владелец вставил из
 * мессенджера код `AMIGO-JY9D-TAVG` и получил «код не найден»; тот же код,
 * набранный руками без дефисов, погасился с первого раза. Разница была в
 * ОДНОМ невидимом знаке: мессенджеры, почтовые клиенты и текстовые редакторы
 * подменяют обычный дефис-минус на типографское тире, а переносы слов
 * оставляют за собой мягкий перенос и метки направления письма. Человек их не
 * видит ни на экране, ни в поле ввода — а `where { code }` по ним не
 * совпадает, и отказ выглядит как «код неправильный».
 *
 * Поэтому здесь не только `-` (U+002D), но и весь ряд тире (U+2010–U+2015,
 * включая неразрывный U+2011), знак минус (U+2212), мягкий перенос (U+00AD) и
 * невидимые знаки нулевой ширины (U+200B–U+200D, U+FEFF). Пробелы любого рода
 * ловит `\s` — он в JS покрывает и неразрывный U+00A0, и U+FEFF, и весь блок
 * U+2000–U+200A.
 *
 * PROGRESS.md 7.151.
 */
const DROPPED = new Set([
  "\u002D", // дефис-минус, обычный
  "\u2010", // hyphen
  "\u2011", // неразрывный дефис
  "\u2012", // figure dash
  "\u2013", // en dash — то самое типографское тире из мессенджера
  "\u2014", // em dash
  "\u2015", // horizontal bar
  "\u2212", // minus sign
  "\u00AD", // мягкий перенос, невидим всегда
  "\u200B", // zero width space
  "\u200C", // zero width non-joiner
  "\u200D", // zero width joiner
  "\uFEFF", // BOM / zero width no-break space
]);

/**
 * Кириллические омоглифы → латиница.
 *
 * Раскладка клавиатуры — вторая после тире причина, по которой переписанный
 * код не совпадает: на русской раскладке `С` и `Т` в слове набираются
 * кириллицей, а выглядят ровно как латинские. Отображение делается ПОСЛЕ
 * приведения к верхнему регистру, поэтому строчные буквы (`а`, `м`, `о`)
 * ловятся тем же списком — отдельной строки на каждый регистр не нужно.
 *
 * ПОЧЕМУ ЭТО НЕ ОПАСНО, и это доказано числом, а не рассуждением. Алфавит
 * выпуска `ACCESS_CODE_ALPHABET` — латиница и цифры; ни одна кириллическая
 * буква в него не входит, то есть **0 из 26** знаков алфавита являются
 * источником этого отображения. Значит нормализация — тождество на любой
 * строке, собранной из алфавита: ни один выпущенный код не может превратиться
 * в другой выпущенный код. Утверждение прогоняется по всем 26 знакам в
 * `access-code-format.test.ts`, а не остаётся обещанием в комментарии.
 */
const HOMOGLYPHS = new Map([
  ["\u0410", "A"], // А
  ["\u0412", "B"], // В
  ["\u0415", "E"], // Е
  ["\u041A", "K"], // К
  ["\u041C", "M"], // М
  ["\u041D", "H"], // Н
  ["\u041E", "O"], // О
  ["\u0420", "P"], // Р
  ["\u0421", "C"], // С
  ["\u0422", "T"], // Т
  ["\u0423", "Y"], // У
  ["\u0425", "X"], // Х
]);

/**
 * Одна нормализация на всех: и на записи (скрипт выпуска), и на чтении
 * (маршрут погашения).
 *
 * Верхний регистр, выброшены пробелы, все начертания дефиса и невидимые
 * знаки, кириллические омоглифы отображены в латиницу. Дефисы — потому что
 * код печатается человеку группами (`AMIGO-K7M2-QW9F`), и переписать его без
 * дефисов так же законно, как с ними. Уникальность в базе стоит на уже
 * нормализованном значении, поэтому она настоящая, а не «уникальность с
 * точностью до регистра».
 *
 * Разойдись эта функция на записи и на чтении хоть в одном знаке — выпущенная
 * партия перестала бы погашаться, причём молча. Поэтому она одна на весь
 * репозиторий, и вызывающих у неё ровно четверо: маршрут погашения
 * (`src/lib/access-code.ts`), стенд e2e, скрипт выпуска и скрипт отзыва.
 */
export function normalizeAccessCode(raw: string): string {
  let out = "";
  // По кодовым точкам, а не по «символам»: суррогатные пары не должны
  // разваливаться пополам по дороге.
  for (const ch of raw.toUpperCase()) {
    if (DROPPED.has(ch)) continue;
    // \s в JS покрывает \u00A0, \uFEFF и весь блок U+2000–U+200A — то есть
    // все пробельные знаки, которые приносит вставка из буфера.
    if (/\s/.test(ch)) continue;
    out += HOMOGLYPHS.get(ch) ?? ch;
  }
  return out;
}

/** Как код показывают человеку: приставка, потом группы по четыре. */
export function formatAccessCode(code: string, prefix: string): string {
  const body = code.slice(prefix.length);
  return [prefix, ...(body.match(/.{1,4}/g) ?? [])].join("-");
}
