/**
 * Один канонический хост, и правило, которое сводит к нему второй.
 *
 * Замер на живом проде 05.09.2026: `www.rusofacilapp.com` отвечает
 * **200**, а не редиректом, на URL всех типов — корень локали, страница
 * урока, страница пазла, страница категории, `robots.txt`, `sitemap.xml`.
 * То есть весь набор адресов сайта существует дважды, и 1912 URL карты
 * сайта — это 3824 адреса, по которым краулер может ходить.
 *
 * Почему это не «просто лишний хост». Склейка ожидаема: `rel=canonical`
 * и все три `hrefLang` на www-версии абсолютные и указывают на апекс
 * (проверено на трёх страницах), `sitemap.xml` и `robots.txt` на обоих
 * хостах побайтово одинаковы и называют только апекс. Но canonical —
 * это подсказка, а не команда: краулер обязан СНАЧАЛА скачать страницу,
 * чтобы её прочитать. У сайта, где каждый HTML-ответ идёт с
 * `cache-control: private, no-cache, no-store` и `x-vercel-cache: MISS`,
 * каждый такой обход — полный рендер. Редирект отвечает тем же ответом
 * без рендера вообще.
 *
 * Правило нарочно выделено в чистую функцию: у него ровно один вход
 * (заголовок `Host`) и ровно один выход (адрес или «не трогать»), и его
 * можно проверить тестом, не поднимая ни сервера, ни запроса.
 */
import { SITE_URL } from "@/lib/site";

const CANONICAL_HOST = new URL(SITE_URL).host;
const WWW_PREFIX = "www.";

/**
 * Куда вести запрос, пришедший на `Host`, — или `null`, если он уже на
 * каноническом хосте и трогать его нельзя.
 *
 * Целевой адрес собирается из `SITE_URL`, а не из входящего хоста с
 * отрезанным «www.». Так адрес редиректа и адрес в `rel=canonical`
 * строятся из ОДНОЙ константы и разойтись не могут — а «отрезать
 * префикс» разошлось бы в тот же день, когда появится третий хост
 * (превью-домен Vercel, кастомный домен приложения) и его начнут резать
 * тем же правилом.
 *
 * Порт из заголовка игнорируется намеренно: `www.` на localhost не
 * бывает, а превью-домены Vercel (`*.vercel.app`) сюда не попадают —
 * условие проверяет ровно префикс «www.», а не «всё, что не апекс».
 * Сводить превью к проду было бы совсем другим решением: превью-деплой
 * должен оставаться открываемым по своему адресу.
 */
export function apexRedirectTarget(
  host: string | null,
  pathname: string,
  search: string,
): string | null {
  if (!host) return null;
  const bare = host.toLowerCase().split(":")[0];
  if (!bare.startsWith(WWW_PREFIX)) return null;
  // Только www перед КАНОНИЧЕСКИМ хостом. `www.example.com`, пришедший
  // на этот сервер по ошибке конфигурации, не наш и не переклеивается.
  if (bare.slice(WWW_PREFIX.length) !== CANONICAL_HOST) return null;
  return `${SITE_URL}${pathname}${search}`;
}

/**
 * 308, а не 301. Оба постоянные и для поиска равнозначны; 308 при этом
 * обязывает клиента сохранить метод и тело, так что POST на www (форма
 * входа, вебхук, отправка упражнения) доедет POST-ом, а не превратится
 * в GET, как это разрешено делать с 301.
 */
export const APEX_REDIRECT_STATUS = 308;
