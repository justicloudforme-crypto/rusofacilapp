/**
 * ОБРАЩЕНИЕ В РУССКОМ ИНТЕРФЕЙСЕ — 7.199 часть 5б (кабинет), РАСШИРЕНО В
 * 7.200 НА ВЕСЬ СЛОВАРЬ (долг 219).
 *
 * ПРАВИЛО: русский интерфейс обращается на «вы». Испанский на «tú» — и
 * это отдельное утверждение ниже, чтобы правку не растащило на вторую
 * локаль.
 *
 * ПОЧЕМУ ПРАВИЛО ВООБЩЕ ЕСТЬ. Записанного не было; 15.09.2026 посчитали по
 * всему `ru.json` (1446 значений): «вы» — 133 строки, «ты» — 37,
 * пересечения 0. Преобладание больше чем втрое и в 12 разделах из 15 —
 * правило вывели из этого, а не из вкуса.
 *
 * ────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ ПЕРЕПИСЬ 7.199 ОБЪЯВИЛА КАБИНЕТ ЧИСТЫМ, А В НАСТРОЙКАХ СТОЯЛО
 * «Показывай свою серию занятий…» — ОТВЕТ ЧИСЛОМ, И ОН НЕ ТОТ, ЧТО
 * НАПРАШИВАЛСЯ.
 *
 * Напрашивалось «строка живёт в другом файле / в компоненте». Это
 * неверно: `profile.publicProfileDescription` лежит в `ru.json`, строка
 * 616, ВНУТРИ раздела `profile` — того самого, который сторож 7.199 и
 * судил. Промахнулся ДЕТЕКТОР, а не выборка:
 *
 *   · признак «ты» собирался из перечисленных императивов — их было 40, и
 *     «Показывай» среди них нет (список несовершенных форм на «-ай/-яй»
 *     не собирали вовсе: «Приглашай», «Продолжай», «Учись», «Практикуй»,
 *     «Потренируй» — те же пропуски);
 *   · притяжательное искали как «тво…», а в строке стоит «свою» — форма
 *     возвратная и по виду нейтральная.
 *
 * Прогон старого детектора по всему `ru.json` даёт 25 строк на «ты» и
 * НОЛЬ в разделе `profile`. Прогон нынешнего — 40 строк, и две из них
 * (`profile.publicProfileDescription`, `wordGames.subtitle`) старый не
 * видел ни в каком разрезе. Обе величины проверяются ниже подсадками, а
 * не пересказываются.
 *
 * ────────────────────────────────────────────────────────────────────
 * ГРАНИЦА, И ОНА НАЗВАНА, А НЕ ПОДРАЗУМЕВАЕТСЯ. Правило судит ИНТЕРФЕЙС:
 * `ru.json` целиком плюс русские строки, вписанные прямо в страницы
 * админки. Учебный материал под правило не попадает, и это не поблажка:
 * «ты» там — ПРЕДМЕТ урока (в русском есть «ты» и «вы», и курс этому
 * учит), а не обращение к читателю. Файлы названы поимённо в
 * {@link TEACHING_MATERIAL}.
 */

const W = "[А-Яа-яЁё]";
const bounded = (body: string) => new RegExp(`(?<!${W})(?:${body})(?!${W})`, "iu");

/**
 * Императивы второго лица единственного числа. Список ДЛИННЕЕ, чем был:
 * к 40 формам 7.199 добавлены несовершенные на «-ай/-яй» и остальные,
 * которые действительно стоят в этом словаре, — иначе «0 нарушений»
 * значило бы «0 совпадений», как оно и вышло в 7.199.
 */
