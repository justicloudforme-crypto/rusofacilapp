import { describe, expect, it } from "vitest";
import ru from "./ru.json";
import es from "./es.json";

/**
 * ОБРАЩЕНИЕ В РУССКОМ ИНТЕРФЕЙСЕ — 7.199, часть 5б.
 *
 * ЖАЛОБА. Русский кабинет обращался к человеку вперемешку: «Твои значки»
 * рядом с «Получили код-приглашение? Введите его здесь» и «Учите русский
 * язык…».
 *
 * ЗАПИСАННОГО ПРАВИЛА НЕ БЫЛО. Поиск по PROGRESS.md дал одну строку —
 * заметку 7.x о том, что блок `glossary` переводили «регистром соседних
 * блоков, обращение на „ты“», — но это описание одной правки, а не
 * правило, и в коде правила не было вовсе.
 *
 * ПОЭТОМУ СЧИТАЛИ. По всему `ru.json` (1446 значений на 15.09.2026):
 * на «вы» — 133 строки, на «ты» — 37, пересечения 0. Преобладает «вы»
 * больше чем втрое, в 12 разделах из 15. Кабинет к нему и приведён:
 * до правки `profile` держал 22 строки на «вы» и 12 на «ты», после —
 * 34 и 0.
 *
 * ЧТО СТЕРЕЖЁТ ЭТА ПРОВЕРКА, А ЧТО НЕТ. Стережёт РАЗДЕЛ `profile`: он
 * обязан быть целиком на «вы». Остальные разделы намеренно не трогались
 * этим заходом — в `vocabulary` и `wordGames` «ты» остаётся, и
 * переписывать их значило бы менять тексты, о которых никто не просил.
 * Испанский не трогается вовсе: там `tú` — норма и она сплошная.
 */

const W = "[А-Яа-яЁё]";
const bounded = (body: string) => new RegExp(`(?<!${W})(?:${body})(?!${W})`, "iu");

/** Признаки обращения на «ты». Императив второго лица единственного
 *  числа — самый надёжный из них: «Выбери» против «Выберите». */
const TY = [
  bounded("ты"),
  bounded("тебя"),
  bounded("тебе"),
  bounded("тобой"),
  bounded("тво[йяеёиюмх][а-яё]*"),
  bounded(
    "(?:Введи|Нажми|Узнай|Войди|Попробуй|Выбери|Открой|Начни|Продолжи|Повтори|Проверь|Смотри|Слушай|" +
      "Читай|Пиши|Учи|Запомни|Ответь|Реши|Сыграй|Найди|Возьми|Сделай|Расскажи|Добавь|Обнови|Сохрани|" +
      "Отмени|Закрой|Подтверди|Скопируй|Перетащи|Заполни|Придумай|Задай|Отправь|Вернись|Переходи|Жми|Поделись)",
  ),
];

const VY = [
  bounded("вы"),
  bounded("вас"),
  bounded("вам"),
  bounded("вами"),
  bounded("ваш[а-яё]*"),
  bounded(`${W}{3,}(?:ите|йте)`),
];

function flatten(node: unknown, path = "", out: [string, string][] = []): [string, string][] {
  if (typeof node === "string") {
    out.push([path, node]);
    return out;
  }
  if (node && typeof node === "object") {
    for (const [k, v] of Object.entries(node as Record<string, unknown>)) flatten(v, path ? `${path}.${k}` : k, out);
  }
  return out;
}

const onTy = (value: string) => TY.some((r) => r.test(value));
const onVy = (value: string) => VY.some((r) => r.test(value));

const profileStrings = flatten((ru as unknown as Record<string, unknown>).profile, "profile");

describe("русский кабинет обращается на «вы»", () => {
  it("ни одной строки на «ты» в разделе profile", () => {
    const offenders = profileStrings.filter(([, v]) => onTy(v)).map(([p, v]) => `${p} = ${v}`);
    expect(offenders).toEqual([]);
  });

  it("и «вы» там действительно есть — проверка не смотрит в пустоту", () => {
    expect(profileStrings.filter(([, v]) => onVy(v)).length).toBeGreaterThan(20);
  });

  // ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ НА НАСТОЯЩИХ СТРОКАХ ДО ПРАВКИ: все двенадцать
  // обязаны быть пойманы. Список — дословно то, что стояло в `ru.json`
  // 15.09.2026 до этого захода.
  it("подсадка: двенадцать дореформенных строк кабинета ловятся все", () => {
    const before = [
      "Твой первый шаг",
      "Выбери категорию карточек и начни запоминать первые слова.",
      "Чем ты занимался {date}",
      "Серия ни разу не прерывалась: считается с {start} — твоего первого дня.",
      "Твои значки",
      "Твой результат",
      "Поделись своей ссылкой. Когда приглашённый впервые оформит подписку, ты получишь 30 дней бесплатно.",
      "С каждым днём практики русский язык становится тебе ближе и понятнее.",
      "Выбери персонажа и его настроение — изменение сохранится сразу.",
      "Нажми, чтобы сменить аватар",
      "Выбери аватар",
      "Твой ответ",
    ];
    expect(before.filter(onTy)).toHaveLength(12);
  });

  // ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ: детектор не красит «вы»-строки в «ты».
  it("строки на «вы» детектор не считает обращением на «ты»", () => {
    const after = ["Ваши значки", "Выберите аватар", "Нажмите, чтобы сменить аватар", "Чем вы занимались {date}"];
    expect(after.filter(onTy)).toHaveLength(0);
    expect(after.filter(onVy)).toHaveLength(4);
  });

  it("испанский кабинет не тронут: tú остаётся", () => {
    const esProfile = flatten((es as unknown as Record<string, unknown>).profile, "profile");
    expect(esProfile.some(([, v]) => /\btu\b|\btus\b|\bTu\b/.test(v))).toBe(true);
  });
});

describe("род в русском статусе подписки согласован с «подпиской»", () => {
  it("«Отменена», а не «Отменено» — одна форма на обе поверхности", () => {
    const account = (ru as unknown as { profile: Record<string, string> }).profile;
    expect(account.statusCanceled).toBe("Отменена");
    expect(account.statusCanceling.startsWith("Отменена")).toBe(true);
    // И «Отменено» в русском словаре нет вовсе.
    expect(JSON.stringify(ru)).not.toContain("Отменено");
  });
});
