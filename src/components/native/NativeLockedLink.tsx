"use client";

import Link from "next/link";
import type { ReactNode } from "react";
import { usePaywall, type PaywallReason } from "@/contexts/PaywallContext";
import type { LockedKind } from "@/lib/native-access-copy";

/**
 * Плитка закрытого материала ВНУТРИ ОБОЛОЧКИ: тап открывает окно «Этот
 * материал закрыт» с единственной кнопкой «Понятно», а не ведёт на
 * страницу (долг 185, часть 2 захода 7.193).
 *
 * ЧТО БЫЛО. Закрытый РАССКАЗ и закрытый УРОК вели себя по-разному, и
 * владелец увидел это на живом телефоне: рассказ давал окно и кончал
 * разговор, а урок пускал на страницу с четырьмя вкладками, на трёх из
 * которых стояли кнопки «Смотреть тарифы». Две разные реакции на одно и
 * то же положение дел человек читает как два разных положения дел.
 *
 * ПОЧЕМУ ИМЕННО ТАК, А НЕ «ЗАПРЕТИТЬ ПЕРЕХОД». Перехват списан с
 * `StoriesCatalog` (и с `MediaCatalog`, и с `WordGamesPicker`) не из
 * подражания: там этот приём уже оплачен и уже даёт ту реакцию, к которой
 * приводится урок. Ссылка остаётся ссылкой — то есть адрес по-прежнему
 * достижим прямым переходом, — и это намеренно: страница закрытого урока
 * отдаёт грамматику бесплатно всем, включая поисковик, и убирать её из
 * выдачи эта правка не имеет права (замер 7.193: веб не тронут ни на
 * байт, ветка живёт только внутри оболочки).
 *
 * В ВЕБЕ ЭТОТ КОМПОНЕНТ НЕ РЕНДЕРИТСЯ ВОВСЕ — не «прячется», а не
 * попадает в дерево: вызывающая страница ставит его только когда
 * `isNativeShellRequest()`.
 */
export default function NativeLockedLink({
  href,
  className,
  reason = "free",
  kind,
  children,
}: {
  href: string;
  className?: string;
  /** Тип материала: он решает ТЕКСТ окна (7.196, часть 3). Обязателен —
   *  умолчание вернуло бы «относится к закрытой части курса» пазлу. */
  kind: LockedKind;
  /** "premium" — когда материалу нужен именно план Premium, а подписка у
   *  человека уже есть. Дальше решает само окно. */
  reason?: PaywallReason;
  children: ReactNode;
}) {
  const { openPaywall } = usePaywall();
  return (
    <Link
      href={href}
      className={className}
      onClick={(event) => {
        event.preventDefault();
        openPaywall(reason, kind);
      }}
    >
      {children}
    </Link>
  );
}
