"use client";

import { useEffect } from "react";
import { configureRevenueCat, loginRevenueCat, logoutRevenueCat } from "@/lib/revenuecat-client";

/**
 * ПРИВЯЗКА ПОКУПАТЕЛЯ МАГАЗИНА К УЧЁТНОЙ ЗАПИСИ САЙТА — заход 7.224.
 *
 * Ничего не рисует. Единственное, что делает: держит `appUserID` SDK
 * равным `id` вошедшего человека — и сбрасывает его в анонима, когда тот
 * вышел.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ УЗЕЛ, А НЕ СТРОЧКА В ЭКРАНЕ ПОКУПКИ. Экран покупки
 * открывается по тапу на замок, а покупка может прийти и без него: чек
 * восстановлен магазином, подписка продлилась ночью, покупка перенесена с
 * другого аккаунта. Во всех этих случаях RevenueCat присылает событие с
 * тем `app_user_id`, который стоял НА МОМЕНТ ПОКУПКИ, а вебхук ищет по
 * нему пользователя (`/api/webhooks/revenuecat`). Привязка, живущая
 * только внутри экрана покупки, означала бы, что до первого его открытия
 * все события приезжают на анонимный идентификатор и НЕ НАХОДЯТ никого.
 *
 * ВЫХОД ИЗ УЧЁТНОЙ ЗАПИСИ ОБЯЗАН СБРАСЫВАТЬ ПРИВЯЗКУ. Телефон бывает
 * общим: без `logOut` следующий вошедший унаследовал бы чужую покупку.
 */
export default function NativeStoreIdentity({ userId }: { userId: string | null }) {
  useEffect(() => {
    let cancelled = false;
    void (async () => {
      try {
        // ИДЕНТИФИКАТОР ИДЁТ В САМУ НАСТРОЙКУ, а не только в `logIn`
        // (долг 305, 7.228): `configure` без него заводит анонимного
        // клиента, и каждый выход из учётной записи добавлял в консоль
        // RevenueCat ещё одного. Для гостя (`userId === null`) настройка
        // остаётся безымянной — своего идентификатора у него и нет.
        const ready = await configureRevenueCat(userId);
        if (!ready || cancelled) return;
        if (userId) await loginRevenueCat(userId);
        else await logoutRevenueCat();
      } catch {
        // Магазин недоступен (нет сервисов Google, нет сети). Это не
        // повод ронять страницу: покупка просто не заработает, и экран
        // покупки скажет об этом своими словами.
      }
    })();
    return () => {
      cancelled = true;
    };
  }, [userId]);

  return null;
}
