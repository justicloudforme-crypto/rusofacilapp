"use client";

import { useEffect } from "react";
import { SIGNED_OUT_PARAM, personalPageCaches } from "@/lib/signed-out";
import { personalLocalKeys } from "@/lib/signed-out-local";
import { localKeys, removeLocal } from "@/lib/safe-storage";

/**
 * УБОРЩИК ЛИЧНЫХ КОПИЙ ПОСЛЕ ВЫХОДА (заход 7.198, часть 1).
 *
 * Зачем он есть — в шапке `src/lib/signed-out.ts`: выход менял ответ
 * сервера и не трогал ни одной копии страниц вошедшего человека, которые
 * service worker уже сложил себе в кеш.
 *
 * ПОЧЕМУ УБОРКА ЗДЕСЬ, А НЕ В ВОРКЕРЕ. Первый разбор был именно такой —
 * перехватить `POST /api/auth/logout` в `sw.ts` и почистить кеши после
 * ответа. Он неверен, и вот чем. Выход — это отправка ФОРМЫ, то есть
 * навигация. Ответь на неё воркер своим `fetch(request)` — браузер
 * покажет тело, полученное по редиректу, оставив в адресной строке
 * `/api/auth/logout`: воркер отвечает на запрос, а не на его конечную
 * точку. Цена «почистить кеш» оказалась бы сломанным адресом после
 * каждого выхода.
 *
 * Со страницы уборка и проще, и полнее: `caches` доступен окну ровно так
 * же, как воркеру, источник тот же, и никакого протокола между ними не
 * нужно. Работает и тогда, когда воркер ещё не управляет страницей —
 * а сразу после переустановки приложения это обычное дело.
 *
 * ПОЧЕМУ ПРИЗНАК В АДРЕСЕ. Другого способа отличить «эта страница открыта
 * сразу после выхода» от «эта страница открыта гостем» у клиента нет:
 * обе выглядят одинаково, потому что обе и есть гостевые. Признак ставит
 * сам маршрут выхода (`/api/auth/logout`), а страница его тут же
 * стирает из адреса — чтобы он не уехал ни в закладку, ни в историю, ни
 * в `canonical`.
 *
 * ВТОРОЕ ХРАНИЛИЩЕ — 7.199, часть 2. Кешей документов мало: учебная
 * история живёт ещё и в localStorage, и после выхода гость видел блок
 * «Продолжить» прежнего пользователя (снято на телефоне 15.09.2026).
 * Список ключей и разбор, почему гостевой прогресс до входа отделить
 * нечем, — в шапке `src/lib/signed-out-local.ts`. Уборщик один, потому
 * что момент один; хранилища два, и чистятся они по отдельности.
 */
export default function SignedOutCachePurge() {
  useEffect(() => {
    const url = new URL(window.location.href);
    if (url.searchParams.get(SIGNED_OUT_PARAM) !== "1") return;

    url.searchParams.delete(SIGNED_OUT_PARAM);
    window.history.replaceState(null, "", url.pathname + url.search + url.hash);

    // Хранилища два, и падение одного не отменяет уборку другого.
    // Приватное окно, запрет на сайт, переполнение — уборка не условие
    // выхода: `localKeys()` вернёт пустой список, удалять будет нечего,
    // и ронять из-за этого страницу нечем.
    for (const key of personalLocalKeys(localKeys())) removeLocal(key);

    if (typeof caches === "undefined") return;
    void (async () => {
      try {
        const names = personalPageCaches(await caches.keys());
        await Promise.all(names.map((name) => caches.delete(name)));
      } catch {
        // То же самое про хранилище кешей.
      }
    })();
  }, []);

  return null;
}
