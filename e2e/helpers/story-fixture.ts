import type { APIRequestContext } from "@playwright/test";

/**
 * В КАКОЙ ФОРМЕ БАЗА ПОД СЕРВЕРОМ — В ФОРМЕ CI ИЛИ В ФОРМЕ НОУТБУКА.
 *
 * ЗАЧЕМ. `e2e/story-spanish-title.spec.ts` опирается на три строки из
 * `e2e/fixtures/stories.json`, которые в базу кладёт
 * `scripts/seed-e2e-fixture.mjs`. А тот НАМЕРЕННО отказывается писать в
 * базу с настоящим содержимым (`assertSafeToSeed`): `dev.db` в корне
 * репозитория — это боевой банк содержимого, и запись фикстуры поверх
 * него переписала бы настоящие строки под сохранённым прогрессом живых
 * людей. Значит на машине разработчика этих трёх рассказов нет и быть не
 * может: замер 18.09.2026 — в `dev.db` 325 рассказов и **0** строк
 * фикстуры.
 *
 * Отсюда дюжина красных проб на каждом локальном прогоне (6 проверок × 2
 * проекта). Краснели они в 7.204, в 7.211 и в 7.212, каждый раз
 * объяснялись словами и каждый раз съедали внимание. Сделать их зелёными
 * на полной базе нельзя честно: одна из проверок утверждает, что
 * серверный указатель каталога называет РОВНО столько рассказов, сколько
 * их в фикстуре, — на 325 настоящих строках это утверждение ложно по
 * построению и «починка» его была бы враньём.
 *
 * Поэтому пропуск, но пропуск ГРОМКИЙ и по измеренному условию, а не по
 * `process.env.CI`. Разница принципиальная: гейт по переменной окружения
 * — это ровно то, чем CI однажды исполнил 25 проб из 49 и отрапортовал
 * зелёным (PROGRESS.md 7.52). Здесь спрашивается САМА БАЗА через сервер,
 * поэтому:
 *   — в CI, где фикстура посеяна, условие ложно и не пропускается ничего;
 *   — если фикстуру в CI однажды перестанут сеять, пробы пропустятся, и
 *     `scripts/check-e2e-coverage.mjs --report=` уронит прогон: любая
 *     пропущенная проба в отчёте — красный выход, отдельно от белого
 *     списка исходников.
 */
export interface StoryFixtureShape {
  present: boolean;
  why: string;
}

/** Первый рассказ фикстуры — он же зонд. Держится в одном экземпляре на
 * весь файл спеки: спрашивать сервер шесть раз подряд об одном и том же
 * незачем. */
let probe: Promise<StoryFixtureShape> | null = null;

export function storyFixtureShape(
  request: APIRequestContext,
  probeStoryId = "e2e-fixture-story-camaleon"
): Promise<StoryFixtureShape> {
  probe ??= (async () => {
    const response = await request.get(`/es/stories/${probeStoryId}`);
    const present = response.status() === 200;
    return {
      present,
      why: present
        ? `рассказ фикстуры ${probeStoryId} отвечает 200 — база в форме CI`
        : `рассказ фикстуры ${probeStoryId} отвечает ${response.status()}: ` +
          `фикстура в базу не посеяна (scripts/seed-e2e-fixture.mjs отказывается писать ` +
          `в базу с настоящим содержимым — см. assertSafeToSeed)`,
    };
  })();
  return probe;
}
