import { expect, type Page } from "@playwright/test";

/**
 * Ставит аккаунту день занятия ДЕЙСТВИЕМ.
 *
 * До 17.09.2026 в пробах на этом месте стоял один GET — открытие
 * `/es/vocabulary` или страницы урока: правилом было «занятие = открытие
 * страницы». 17.09.2026 владелец это правило отменил (заход 7.204): день
 * ставит действие. Поэтому пробе теперь нужно СДЕЛАТЬ что-нибудь, и
 * дешевле всего — ответить на одну карточку: `POST
 * /api/flashcard-progress` и есть тот единственный писатель, на котором
 * стоит отметка дня для словаря и для идиом.
 *
 * Запрос уходит из контекста браузера, то есть с кукой сессии, и
 * отвечает синхронно — отметка успевает записаться до следующего
 * перехода (`markStudyDayVisit` откладывает запись через `after()`, но
 * `after()` держит запрос живым до конца).
 */
export async function markStudyDayByAction(page: Page): Promise<void> {
  const response = await page.context().request.post("/api/flashcard-progress", {
    data: { cardId: "e2e-study-day-card", known: true },
  });
  expect(response.status(), "ответ в карточке обязан пройти — на нём стоит день занятия").toBe(200);
}
