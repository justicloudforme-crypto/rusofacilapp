import { expect, type Page } from "@playwright/test";

/**
 * ПРИЗНАК САМОЙ СТРАНИЦЫ — ДОЛГ 96 (заход 7.217).
 *
 * Строка долга дословно про этот файл: «правило „у каждого замера есть
 * признак самой страницы“ и „сколько объектов измерено — печатается
 * числом“ держится сегодня только соглашением».
 *
 * ЧТО СЧИТАЕТСЯ ПРИЗНАКОМ. Собственный `canonical` страницы. Он выбран не
 * за красоту, а потому что это единственная разметка, которая на этом
 * сайте:
 *
 *   * есть у КАЖДОГО маршрута (`routeAlternates` в `src/lib/site.ts`, и
 *     `route-metadata.test.ts` роняет прогон на маршруте без неё);
 *   * называет ИМЕННО ЭТОТ адрес вместе с локалью — то есть отличает
 *     `/ru/courses` от `/es/courses`, чего не делает ни один `h1`;
 *   * ОТСУТСТВУЕТ на экране отказа и на переписанном 404 — а именно они
 *     и есть те «200 и пустота», ради которых правило написано.
 *
 * Замер, стоящий за этим выбором (07.09.2026, инцидент №1): страница
 * отдавала 200 и рисовала «Something went wrong», а `h1` на ней был —
 * `h1` есть у каждой страницы сайта. Утверждение о видимости `h1`
 * оставалось истинным десять дней подряд.
 */
export async function expectPageIsItself(page: Page, path: string, what = path) {
  const canonical = page.locator('link[rel="canonical"]');
  const href = await canonical.first().getAttribute("href");
  expect(href, `${what}: у страницы нет собственного canonical — она отдала 200, но это не она`).toBeTruthy();
  expect(new URL(href!).pathname.replace(/\/$/, ""), `${what}: canonical называет другой адрес`).toBe(
    path.replace(/\/$/, ""),
  );
}
