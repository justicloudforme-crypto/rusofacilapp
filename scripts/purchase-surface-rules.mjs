/**
 * ЧТО СЧИТАЕТСЯ ПРИЗЫВОМ К ПОКУПКЕ — ОДНО ОПРЕДЕЛЕНИЕ НА ТРИ ПРОВЕРКИ.
 *
 * Читают отсюда: `check-native-payments.mjs` (исходники и живая отдача по
 * http) и `check-rendered-purchase-surfaces.mjs` (отрисованный документ в
 * браузере). Раньше у каждой половины был свой список подписей, и ровно
 * поэтому вторая ловила то, чего не ловила первая, — а отчёт складывал их
 * нули в один общий ноль.
 *
 * ====================================================================
 * ПРИЗНАК ИЩЕТСЯ ПО СМЫСЛУ, А НЕ ПО ОДНОЙ СТРОКЕ
 * ====================================================================
 *
 * Три независимых признака, и нарушением считается любой:
 *
 *   1. ЦЕЛЬ. Орган управления ведёт на платёжную поверхность: `/pricing`,
 *      `/checkout`, `/api/checkout`, домен Stripe — в любом написании,
 *      включая `?next=…` и включая написанное во flight-разметке.
 *   2. СИЛЬНАЯ ПОДПИСЬ. Текст самого органа прямо зовёт оформить
 *      подписку. Такие подписи — нарушение всегда, куда бы орган ни вёл.
 *   3. СЛАБОЕ СЛОВО В РОЛИ ОРГАНА. «Precios», «Цены», «тариф», «Premium»,
 *      «Suscríbete» на кнопке БЕЗ адреса или на органе, ведущем на
 *      платёжную поверхность. Без второй половины этого правила слово
 *      «Premium» на значке уровня C1 считалось бы нарушением, а это
 *      честная метка, и магазины её разрешают.
 *
 * ЧТО СЮДА НАМЕРЕННО НЕ ВОШЛО. «Ver los cursos» владелец назвал как
 * подозрительную подпись. Замер: `home.heroCta` ведёт на `/es/courses` —
 * это навигация по курсу, а не покупка, и на живом телефоне под ней
 * открывается список уроков. В сильные подписи она поэтому не внесена; в
 * слабые — тоже, потому что по слабому правилу она попадала бы под
 * подозрение на каждой странице и не попадала бы ни разу законно. Если
 * когда-нибудь эта кнопка начнёт вести на `/pricing`, её поймает правило
 * 1, то есть цель, а не текст.
 */

/** Платёжные поверхности. Ловит и `/ru/pricing?next=/ru/courses/a1/2`. */
export const PAYMENT_TARGET = /(^|\/)(pricing|checkout)(\/|\?|#|$)|\/api\/checkout|(^|\/\/|\.)stripe\.com/i;

/** Подписи, которые сами по себе — призыв оформить подписку. */
export const STRONG_PURCHASE =
  /Оформит[ьея] подписку|Оформите подписку|Посмотреть тарифы|Смотреть тарифы|Продлить подписку|Подписаться|Ver (?:los )?planes|Ver precios|Suscr[ií]bete|Suscribirme|Suscribirse/i;

/** Слова, которые платные только в роли органа управления. */
export const WEAK_PURCHASE = /(^|\W)(Precios|Цены|тариф\w*|Premium|Suscripci[óo]n|подписк\w+)(\W|$)/i;

/** Один орган управления, приведённый к трём полям. */
export function judgeControl({ text, target, isControl = true }) {
  const problems = [];
  const label = (text ?? "").replace(/\s+/g, " ").trim();
  const to = (target ?? "").trim();
  if (to && PAYMENT_TARGET.test(to)) {
    problems.push(`ведёт на платёжную поверхность: ${to}`);
  }
  if (isControl && STRONG_PURCHASE.test(label)) {
    problems.push(`подпись прямо зовёт оформить подписку: «${label.slice(0, 80)}»`);
  }
  // СЛАБОЕ слово судится только на КОРОТКОЙ подписи — той, где оно и есть
  // весь смысл кнопки («Цены», «Precios», «Premium»).
  //
  // Заплачено первым же прогоном перестроенного прибора: плитка темы
  // словаря называется «🛍️ Покупки и цены · 248 слов» (по-испански
  // «Compras y precios»), это СОДЕРЖИМОЕ курса, а не касса, и по слабому
  // правилу без ограничения длины она краснела во всех трёх ролях на обеих
  // локалях. Порог — три слова: подпись кассы короткая всегда, подпись
  // темы — почти никогда.
  const words = label
    .replace(/[^\p{L}\p{N}\s]/gu, " ")
    .split(/\s+/)
    .filter(Boolean);
  if (isControl && words.length <= 3 && WEAK_PURCHASE.test(label) && (!to || PAYMENT_TARGET.test(to))) {
    problems.push(
      `платное слово на органе без адреса или на органе, ведущем к оплате: «${label.slice(0, 80)}»` +
        (to ? ` → ${to}` : " (кнопка без href — ровно так был написан долг 191)"),
    );
  }
  return problems;
}

/** Каждый адрес платёжной поверхности в сыром ответе: `href`, `action`,
 *  `formaction`, и то же самое внутри экранированной flight-разметки. */
export function paymentTargetsInHtml(raw) {
  const out = [];
  const attr = /(?:href|action|formaction)=\\?"([^"\\]+)\\?"/gi;
  let m;
  while ((m = attr.exec(raw)) !== null) {
    if (PAYMENT_TARGET.test(m[1])) out.push(m[1]);
  }
  return out;
}

/**
 * ВИДИМЫЙ документ: всё, кроме `<script>` и `<template>`.
 *
 * Граница названа числом и её надо знать. Словарь уезжает во
 * flight-разметку КАЖДОЙ страницы целиком (`Navbar`, `Footer` и
 * `BottomNav` — клиентские компоненты и получают `dict` ЦЕЛИКОМ),
 * поэтому в сыром HTML `/ru/vocabulary` строка «Оформить подписку»
 * встречается 4 раза даже там, где на экране её нет ни разу. Судить по
 * сырому HTML значило бы краснеть на каждой странице сайта.
 *
 * Обратная сторона той же границы — причина долга 191: кнопку,
 * нарисованную клиентом ПОСЛЕ ответа сервера, эта проверка не видит в
 * принципе. Её ловит вторая половина, `check-rendered-purchase-surfaces`,
 * которая открывает страницу браузером.
 */
export function visibleDocument(html) {
  return html
    .replace(/<script[\s\S]*?<\/script>/gi, " ")
    .replace(/<template[\s\S]*?<\/template>/gi, " ");
}

/**
 * ВСЕ подписи покупки из обоих словарей — перепись, а не рукописный
 * список (долг 191, причина №2).
 *
 * Возвращает `[{ locale, key, value }]`. Именно этот набор обязан
 * проходить через ветку на оболочку или через её единственную точку.
 */
export function purchaseCtaKeys(dictionaries) {
  const found = [];
  for (const [locale, dict] of Object.entries(dictionaries)) {
    const walk = (node, keyPath) => {
      if (typeof node === "string") {
        if (STRONG_PURCHASE.test(node)) found.push({ locale, key: keyPath.join("."), value: node });
        return;
      }
      if (node && typeof node === "object") {
        for (const key of Object.keys(node)) walk(node[key], [...keyPath, key]);
      }
    };
    walk(dict, []);
  }
  return found;
}
